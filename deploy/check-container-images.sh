#!/usr/bin/env bash
# Build and smoke-test the images that the `container` deployment target generates
# (spec §6.8), for Python and for R, from this checkout.
#
# Golden-file comparisons and hadolint only prove the Dockerfiles are well formed.
# This script proves they build and run: each image is built, started without SAS
# credentials, and must turn healthy, serve the app with Bootstrap 5, run as uid
# 10001, have Java 17 and load saspy (through reticulate for R).
#
# The released SAShiny packages are swapped for this checkout: the PyPI pin is
# replaced with a wheel built here, and the R `install_github()` line with
# `install_local()` of R/. Every other line is the generated Dockerfile.
#
# Run from the repository root (needs docker and uv; no SAS account):
#
#   bash deploy/check-container-images.sh [work-dir]
#
# LANGUAGES="python" or LANGUAGES="r" checks one image only.

set -euo pipefail

REPO=$(cd "$(dirname "$0")/.." && pwd)
WORK=${1:-$(mktemp -d)}
PLATFORM=linux/amd64
HEALTH_TIMEOUT=${HEALTH_TIMEOUT:-180}
LANGUAGES=${LANGUAGES:-python r}
mkdir -p "$WORK"
containers=()
cleanup() {
  # The +-expansion keeps an empty array safe under `set -u` in bash 3.2 (macOS).
  for c in ${containers[@]+"${containers[@]}"}; do docker rm -f "$c" > /dev/null 2>&1 || true; done
}
trap cleanup EXIT

fail() { echo "FAIL: $*" >&2; exit 1; }

generate() { # language out-dir
  (cd "$REPO/Python" && uv run --no-dev python - "$1" "$2" << 'EOF'
import sys
from sashiny import deploy as d

language, out = sys.argv[1], sys.argv[2]
profile = {"name": "oda", "method": "iom", "oda_region": "us1"}
d.deploy("../examples/general", "container", out, profile, license_ack=True, language=language)
EOF
  )
}

replace_line() { # file old new: replace one exact substring, which must be present
  python3 - "$@" << 'EOF'
import pathlib, sys
path, old, new = sys.argv[1:]
p = pathlib.Path(path)
text = p.read_text()
if text.count(old) != 1:
    sys.exit(f"{path}: expected exactly one occurrence of {old!r}")
p.write_text(text.replace(old, new))
EOF
}

smoke() { # language image
  local language=$1 image=$2 name="sashiny-check-$1-$$"
  echo "== run $image"
  docker run -d --name "$name" --platform "$PLATFORM" -p 127.0.0.1::8000 \
    -e SASHINY_LICENSE_ACK=true -e SASHINY_PROFILE=oda -e SASHINY_ODA_REGION=us1 \
    "$image" > /dev/null
  containers+=("$name")

  local status=starting waited=0
  while [ "$status" = starting ] && [ "$waited" -lt "$HEALTH_TIMEOUT" ]; do
    sleep 5; waited=$((waited + 5))
    status=$(docker inspect -f '{{.State.Health.Status}}' "$name")
  done
  if [ "$status" != healthy ]; then
    docker logs "$name" 2>&1 | tail -30
    fail "$language image is $status after ${waited}s"
  fi

  local port page
  port=$(docker port "$name" 8000/tcp | head -1 | sed 's/.*://')
  page=$(curl -fsS "http://127.0.0.1:$port/")
  grep -q "Summarise" <<< "$page" || fail "$language app page does not show the program"
  if grep -q "bootstrap-3" <<< "$page"; then fail "$language app page serves Bootstrap 3"; fi

  [ "$(docker exec "$name" id -u)" = 10001 ] || fail "$language image does not run as uid 10001"
  # Capture first: `grep -q` closing the pipe early would fail the pipeline under pipefail.
  local java
  java=$(docker exec "$name" java -version 2>&1 || true)
  grep -q '"17\.' <<< "$java" || fail "$language image has no Java 17"

  if [ "$language" = python ]; then
    docker exec "$name" python -c "import saspy, sashiny, shiny, plotnine" \
      || fail "python image cannot import its packages"
  else
    docker exec "$name" Rscript -e '
      library(SAShiny)
      stopifnot(requireNamespace("ggplot2", quietly = TRUE))
      reticulate::import("saspy")  # fails when libpython is missing
    ' || fail "r image cannot load SAShiny, ggplot2 or saspy"
  fi
  echo "ok: $language image"
}

wants() { [[ " $LANGUAGES " == *" $1 "* ]]; }

# --- Python -------------------------------------------------------------------
if wants python; then
py="$WORK/python"
rm -rf "$py"
generate python "$py"
(cd "$REPO/Python" && uv build --wheel --out-dir "$py/wheel" > /dev/null)
wheel=$(basename "$(ls "$py"/wheel/sashiny-*.whl)")
version=$(sed -n 's/^# Generated by SAShiny \([^ ]*\) .*/\1/p' "$py/Dockerfile")
[ -n "$version" ] || fail "cannot read the SAShiny version from the generated Dockerfile"
replace_line "$py/Dockerfile" \
  "RUN pip install --no-cache-dir \"sashiny[shiny,saspy,upload,plotnine]==$version\"" \
  "COPY wheel/ /tmp/wheel/
RUN pip install --no-cache-dir \"/tmp/wheel/${wheel}[shiny,saspy,upload,plotnine]\""
printf '!wheel/\n' >> "$py/.dockerignore"
echo "== build python image"
docker build --platform "$PLATFORM" -t sashiny-check-python "$py"
smoke python sashiny-check-python
fi

# --- R ------------------------------------------------------------------------
if wants r; then
r="$WORK/r"
rm -rf "$r"
generate r "$r"
version=$(sed -n 's/^# Generated by SAShiny \([^ ]*\) .*/\1/p' "$r/Dockerfile")
[ -n "$version" ] || fail "cannot read the SAShiny version from the generated Dockerfile"
mkdir -p "$r/rsrc"
(cd "$REPO/R" && cp -R DESCRIPTION NAMESPACE LICENSE LICENSE.md NEWS.md R inst man "$r/rsrc/")
replace_line "$r/Dockerfile" \
  "remotes::install_github(\"procogia/SAShiny/R@r-v$version\", upgrade = \"never\")" \
  "remotes::install_local(\"/tmp/rsrc\", upgrade = \"never\")"
replace_line "$r/Dockerfile" "ENV RETICULATE_PYTHON=/opt/saspy/bin/python
" "ENV RETICULATE_PYTHON=/opt/saspy/bin/python
COPY rsrc/ /tmp/rsrc/
"
printf '!rsrc/\n' >> "$r/.dockerignore"
echo "== build r image"
docker build --platform "$PLATFORM" -t sashiny-check-r "$r"
smoke r sashiny-check-r
fi

echo "All container images passed."
