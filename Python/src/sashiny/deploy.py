"""Deployment targets (spec ``CONTRACT.md`` §6.8).

:func:`deploy` turns an app directory into deployment artifacts for one hosting
platform. ``generate`` never touches the network or runs programs. ``apply``
is a separate, explicit step that runs the platform CLI through a replaceable
command runner. ``doctor`` checks local prerequisites without printing values.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .profiles import Profile, parse_profile
from .publish import bundle_files

__all__ = [
    "DeployResult",
    "Runner",
    "Target",
    "deploy",
    "doctor",
    "subprocess_runner",
    "targets",
]

Runner = Callable[[Sequence[str], Mapping[str, str]], int]
_MAX_PORT = 65535

GENERATED_APP_PY = (
    "# Generated by SAShiny (CONTRACT.md 6.8). Serves every contract in this folder.\n"
    "from pathlib import Path\n"
    "\n"
    "import sashiny\n"
    "\n"
    "HERE = Path(__file__).resolve().parent\n"
    'CONTRACTS = sorted(HERE.rglob("*.sashiny.yml"))\n'
    "app = sashiny.app(CONTRACTS, sashiny.Pool(sashiny.connect_from_env, max_size=2), "
    'title="SAShiny")\n'
)
GENERATED_APP_R = (
    "# Generated by SAShiny (CONTRACT.md 6.8). Serves every contract in this folder.\n"
    "library(SAShiny)\n"
    "\n"
    'contracts <- sort(list.files(".", pattern = "[.]sashiny[.]yml$", recursive = TRUE, '
    "full.names = TRUE))\n"
    'sas_app(contracts, sas_pool(sas_connect_env, max_size = 2L), title = "SAShiny")\n'
)
DOCKERIGNORE = "*\n!bundle/\n"


@dataclass
class DeployResult:
    """What :func:`deploy` generated (and, with ``apply``, ran)."""

    target: str
    language: str
    out_dir: Path
    files: list[str]
    excluded: list[str]
    env: list[tuple[str, str]]
    secrets: list[str]
    endpoints: list[str]
    commands: list[list[str]] = field(default_factory=list)


@dataclass(frozen=True)
class Target:
    """A deployment target registry entry (spec §6.8)."""

    id: str
    label: str
    languages: tuple[str, ...]
    options: tuple[str, ...]
    generate: Callable[[_Context], dict[str, str]]
    private_network_option: str = "private_network"
    needs_java_runtime: bool = True
    apply: Callable[[_Context, DeployResult, Runner], list[list[str]]] | None = None
    doctor: Callable[[Runner], list[str]] | None = None


@dataclass
class _Context:
    app_dir: Path
    profile: Profile
    language: str
    options: dict[str, Any]
    version: str


def _package_version() -> str:
    from . import __version__  # noqa: PLC0415 - avoid an import cycle

    return __version__


def _port(options: Mapping[str, Any]) -> int:
    port = options.get("port", 8000)
    if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= _MAX_PORT:
        raise ValueError("port must be an integer from 1 to 65535")
    return port


def dockerfile(language: str, needs_java: bool, port: int, version: str) -> str:
    """Return the ``container`` target's Dockerfile (spec §6.8), byte-exact."""
    head = f"# Generated by SAShiny {version} (CONTRACT.md 6.8). Do not edit by hand.\n"
    tail = (
        "RUN useradd --create-home --uid 10001 sashiny\n"
        "WORKDIR /app\n"
        "COPY --chown=sashiny:sashiny bundle/ /app/\n"
        "USER sashiny\n"
        f"ENV PORT={port}\n"
        f"EXPOSE {port}\n"
    )
    if language == "python":
        java = (
            "RUN apt-get update \\\n"
            " && apt-get install -y --no-install-recommends openjdk-17-jre-headless \\\n"
            " && rm -rf /var/lib/apt/lists/*\n"
            if needs_java
            else ""
        )
        return (
            head
            + "FROM python:3.12-slim\n"
            + java
            + "RUN pip install --no-cache-dir "
            + f'"sashiny[shiny,saspy,upload,plotnine]=={version}"\n'
            + tail
            + "HEALTHCHECK --interval=30s --timeout=5s --start-period=30s --retries=3 \\\n"
            + '  CMD python -c "import urllib.request; '
            + f"urllib.request.urlopen('http://127.0.0.1:{port}/', timeout=4)\"\n"
            + 'CMD ["sh", "-c", "exec shiny run app.py --host 0.0.0.0 --port \\"$PORT\\""]\n'
        )
    java_line = "      openjdk-17-jre-headless \\\n" if needs_java else ""
    return (
        head
        + "FROM rocker/r-ver:4.5.2\n"
        + "RUN apt-get update \\\n"
        + " && apt-get install -y --no-install-recommends \\\n"
        + java_line
        + "      python3 python3-venv curl libcurl4-openssl-dev libssl-dev \\\n"
        + " && rm -rf /var/lib/apt/lists/*\n"
        + "RUN python3 -m venv /opt/saspy \\\n"
        + ' && /opt/saspy/bin/pip install --no-cache-dir "saspy>=5.100" "pandas>=2.0"\n'
        + "ENV RETICULATE_PYTHON=/opt/saspy/bin/python\n"
        + 'RUN Rscript -e \'install.packages(c("remotes", "shiny", "bslib", "callr", '
        + '"later", "promises", "reticulate"), repos = "https://cloud.r-project.org")\' \\\n'
        + " && Rscript -e 'remotes::install_github(\"procogia/SAShiny/R@r-v"
        + f'{version}", upgrade = "never")\'\n'
        + tail
        + "HEALTHCHECK --interval=30s --timeout=5s --start-period=60s --retries=3 \\\n"
        + f'  CMD curl -fsS "http://127.0.0.1:{port}/" > /dev/null || exit 1\n'
        + 'CMD ["sh", "-c", "exec Rscript -e \\"shiny::runApp(\'/app\', host = \'0.0.0.0\', '
        + "port = as.integer(Sys.getenv('PORT')))\\\"\"]\n"
    )


def _generate_container(ctx: _Context) -> dict[str, str]:
    port = _port(ctx.options)
    return {
        "Dockerfile": dockerfile(ctx.language, ctx.profile.needs_java, port, ctx.version),
        ".dockerignore": DOCKERIGNORE,
    }


def _doctor_container(runner: Runner) -> list[str]:
    del runner
    return [] if shutil.which("docker") else ["docker is not on PATH (needed only to build)"]


_REGISTRY: dict[str, Target] = {}


def register(target: Target) -> Target:
    """Add a target to the registry (used by the target modules)."""
    _REGISTRY[target.id] = target
    return target


register(
    Target(
        id="container",
        label="Container image (Dockerfile)",
        languages=("python", "r"),
        options=("port", "language", "private_network"),
        generate=_generate_container,
        doctor=_doctor_container,
    )
)


def targets() -> list[Target]:
    """Return the registered deployment targets, in id order."""
    _load_targets()
    return [_REGISTRY[k] for k in sorted(_REGISTRY)]


def _load_targets() -> None:
    """Register the platform targets (imported lazily to avoid an import cycle)."""
    from . import targets as _targets  # noqa: F401, PLC0415


def _language(app_dir: Path, requested: str | None) -> tuple[str, bool]:
    has_py = (app_dir / "app.py").is_file()
    has_r = (app_dir / "app.R").is_file()
    if requested is not None:
        if requested not in ("python", "r"):
            raise ValueError("language must be 'python' or 'r'")
        return requested, not (has_py if requested == "python" else has_r)
    if has_py != has_r:
        return ("python" if has_py else "r"), False
    raise ValueError(
        "cannot detect the app language: the folder has "
        + ("both app.py and app.R" if has_py else "neither app.py nor app.R")
        + "; pass language='python' or language='r'"
    )


def _lookup(target: str) -> Target:
    _load_targets()
    spec = _REGISTRY.get(target)
    if spec is None:
        raise ValueError(
            f"unknown deployment target {target!r}; expected one of {sorted(_REGISTRY)}"
        )
    return spec


def _validate(  # noqa: PLR0913 - the checks of spec §6.8, in order
    spec: Target,
    app_dir: str | Path,
    profile: Mapping[str, Any] | Profile | None,
    *,
    license_ack: bool,
    version: str | None,
    options: dict[str, Any],
) -> tuple[_Context, bool]:
    """Run the §6.8 checks in order: licence, profile, private network, options, language."""
    if not license_ack:
        raise ValueError(
            "deploying requires license_ack = TRUE: confirm the deployed app runs programs only "
            "on a SAS system you are licensed to use"
        )
    if profile is None:
        raise ValueError("a SAS connection profile is required")
    prof = profile if isinstance(profile, Profile) else parse_profile(dict(profile))
    if prof.requires_vpn and not options.get(spec.private_network_option):
        raise ValueError(
            f"profile {prof.name} requires a private network; pass "
            f"{spec.private_network_option} for target {spec.id}"
        )
    if prof.needs_java and not spec.needs_java_runtime:
        raise ValueError(
            f"target {spec.id} cannot provide Java 17, which profile {prof.name} (iom) needs; "
            "use an http (Viya) profile"
        )
    if "port" in options:
        _port(options)
    root = Path(app_dir).resolve()
    language, generated_app = _language(root, options.get("language"))
    if language not in spec.languages:
        raise ValueError(f"target {spec.id} does not support language {language}")
    return _Context(
        root, prof, language, dict(options), version or _package_version()
    ), generated_app


def _write(root: Path, out: Path, artifacts: Mapping[str, str]) -> tuple[list[str], list[str]]:
    """Copy the bundle and write the artifacts; return (written files, excluded files)."""
    if out.exists() and any(out.iterdir()):
        raise ValueError(f"out_dir must be empty or absent: {out}")
    files, excluded = bundle_files(root)
    written: list[str] = []
    for rel in files:
        dest = out / "bundle" / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / rel, dest)
        written.append(f"bundle/{rel}")
    for rel, text in artifacts.items():
        dest = out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(text.encode("utf-8"))
        written.append(rel)
    return sorted(set(written), key=lambda p: p.encode("utf-8")), excluded


def subprocess_runner(args: Sequence[str], env: Mapping[str, str]) -> int:
    """Run a command, streaming its output (the default ``apply`` runner)."""
    return subprocess.run(list(args), env=dict(env), check=False).returncode  # noqa: S603


def deploy(  # noqa: PLR0913 - the documented deploy surface
    app_dir: str | Path,
    target: str,
    out_dir: str | Path | None = None,
    profile: Mapping[str, Any] | Profile | None = None,
    *,
    license_ack: bool = False,
    apply: bool = False,
    runner: Runner | None = None,
    version: str | None = None,
    **options: Any,
) -> DeployResult:
    """Generate (and optionally apply) deployment artifacts (spec §6.8).

    Args:
        app_dir: The app directory (``app.py`` or ``app.R`` plus contracts and
            programs, or just contracts: an app is then generated).
        target: A target id from :func:`targets`.
        out_dir: Output directory (created; must be empty or absent). Defaults
            to ``<app_dir>-deploy-<target>`` next to the app directory.
        profile: The SAS connection profile (mapping or :class:`Profile`).
        license_ack: Must be ``True``: confirms the deployed app runs programs
            only on a SAS system you are licensed to use.
        apply: Also run the platform CLI (never in tests without a fake runner).
        runner: Command runner for ``apply`` and ``doctor``.
        version: SAShiny version written into artifacts (defaults to this
            package's version; fixtures use ``"0.0.0"``).
        **options: Target options, for example ``port`` or ``language``.

    Returns:
        A :class:`DeployResult` describing the generated files.

    Raises:
        ValueError: For an unknown target, a missing licence acknowledgement, an
            invalid profile or option, or a VPN-only profile without a
            private network.

    """
    spec = _lookup(target)
    ctx, generated_app = _validate(
        spec, app_dir, profile, license_ack=license_ack, version=version, options=options
    )
    artifacts = spec.generate(ctx)
    if generated_app:
        name, text = (
            ("app.py", GENERATED_APP_PY) if ctx.language == "python" else ("app.R", GENERATED_APP_R)
        )
        artifacts[f"bundle/{name}"] = text
    out = Path(out_dir) if out_dir else ctx.app_dir.parent / f"{ctx.app_dir.name}-deploy-{target}"
    files, excluded = _write(ctx.app_dir, out, artifacts)
    prof = ctx.profile
    result = DeployResult(
        target=target,
        language=ctx.language,
        out_dir=out,
        files=files,
        excluded=excluded,
        env=prof.env,
        secrets=prof.secrets,
        endpoints=prof.endpoints,
    )
    if apply:
        if spec.apply is None:
            raise ValueError(f"target {target} has no apply step; follow its generated docs")
        result.commands = spec.apply(ctx, result, runner or subprocess_runner)
    return result


def doctor(target: str, runner: Runner | None = None) -> list[str]:
    """Check local prerequisites for a target; returns problems (empty = ready).

    Messages name tools and variables only, never their values.
    """
    spec = _lookup(target)
    return spec.doctor(runner or subprocess_runner) if spec.doctor else []


def env_missing(names: Sequence[str]) -> list[str]:
    """Names from ``names`` that are unset or empty (values are never returned)."""
    return [n for n in names if not os.environ.get(n)]
