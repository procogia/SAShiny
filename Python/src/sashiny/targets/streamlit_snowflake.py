"""Streamlit in Snowflake target ``streamlit_snowflake`` (spec ``CONTRACT.md`` §6.8.5).

CREATE STREAMLIT: https://docs.snowflake.com/en/sql-reference/sql/create-streamlit
Runtimes: https://docs.snowflake.com/en/developer-guide/streamlit/app-development/runtime-environments
Dependencies: https://docs.snowflake.com/en/developer-guide/streamlit/app-development/dependency-management
Secrets: https://docs.snowflake.com/en/developer-guide/streamlit/app-development/secrets-and-configuration

The container runtime installs Python packages only (no Java, no ssh), so the
target accepts Python apps on http (Viya) profiles. There is no R equivalent.
"""

from __future__ import annotations

import re
import shutil

from ..deploy import DeployResult, Runner, Target, _Context, register
from ..errors import DeployError
from .snowflake import _endpoints, _ident, _snow

__all__ = ["generate"]

_TITLE = re.compile(r"^[^'\"\\\x00-\x1f\x7f]{1,100}$")


def _names(ctx: _Context) -> dict[str, str]:
    o = ctx.options
    if ctx.profile.method != "http":
        raise DeployError("target streamlit_snowflake supports only http (Viya) profiles")
    title = o.get("title", "SAShiny")
    if not isinstance(title, str) or not _TITLE.match(title):
        raise DeployError(
            "title must be 1-100 characters without quotes, backslashes or control characters"
        )
    n = {
        "app": str(_ident(o, "app_name", "SASHINY_STREAMLIT")),
        "database": str(_ident(o, "database", "SASHINY_DB")),
        "schema": str(_ident(o, "schema", "APP")),
        "pool": str(_ident(o, "compute_pool", "SASHINY_STREAMLIT_POOL")),
        "warehouse": str(_ident(o, "warehouse", "SASHINY_WH")),
        "title": title,
    }
    n["fq"] = f"{n['database']}.{n['schema']}"
    n["stage"] = f"{n['fq']}.SASHINY_STAGE"
    n["secret"] = f"{n['fq']}.{n['app']}_SAS_CREDENTIALS"
    return n


def _header(ctx: _Context) -> str:
    return f"-- Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.5). Do not edit by hand."


def _rules(ctx: _Context, n: dict[str, str]) -> list[tuple[str, str, list[str]]]:
    eps = _endpoints(ctx)
    if ctx.options.get("private_connectivity"):
        return [
            (f"{n['fq']}.{n['app']}_SAS_PRIVATE_{i}", "PRIVATE_HOST_PORT", [e])
            for i, e in enumerate(eps, 1)
        ]
    return [(f"{n['fq']}.{n['app']}_SAS_EGRESS", "HOST_PORT", list(eps))]


def _app_py(ctx: _Context, n: dict[str, str]) -> str:
    return "\n".join(
        [
            f"# Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.5). Serves every contract in"
            " this folder.",
            "import os",
            "from pathlib import Path",
            "",
            "import sashiny",
            "from sashiny.streamlit_app import streamlit_app",
            "",
            *[f'os.environ.setdefault("{k}", "{v}")' for k, v in ctx.profile.env],
            "HERE = Path(__file__).resolve().parent",
            'streamlit_app(sorted(HERE.rglob("*.sashiny.yml")), sashiny.connect_from_env,'
            f' title="{n["title"]}")',
            "",
        ]
    )


def _pyproject(ctx: _Context) -> str:
    return "\n".join(
        [
            f"# Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.5). Do not edit by hand.",
            "[project]",
            'name = "sashiny-streamlit-app"',
            'version = "0.0.0"',
            'requires-python = ">=3.11"',
            f'dependencies = ["sashiny[saspy,upload,streamlit]=={ctx.version}"]',
            "",
        ]
    )


def _setup_sql(ctx: _Context, n: dict[str, str]) -> str:
    out = [
        _header(ctx),
        "-- Run with a role that can create databases, warehouses, compute pools and network"
        " rules.",
        f"CREATE DATABASE IF NOT EXISTS {n['database']};",
        f"CREATE SCHEMA IF NOT EXISTS {n['fq']};",
        f"USE SCHEMA {n['fq']};",
        "",
        "CREATE STAGE IF NOT EXISTS SASHINY_STAGE;",
        "",
        f"CREATE WAREHOUSE IF NOT EXISTS {n['warehouse']}",
        "  WAREHOUSE_SIZE = XSMALL",
        "  AUTO_SUSPEND = 60;",
        "",
        f"CREATE COMPUTE POOL IF NOT EXISTS {n['pool']}",
        "  MIN_NODES = 1",
        "  MAX_NODES = 1",
        "  INSTANCE_FAMILY = CPU_X64_XS;",
        "",
    ]
    if ctx.options.get("private_connectivity"):
        out.append(
            "-- Provision a private endpoint for each host first"
            " (SYSTEM$PROVISION_PRIVATELINK_ENDPOINT)."
        )
    for i, (rule, kind, values) in enumerate(_rules(ctx, n)):
        if i:
            out.append("")
        out += [
            f"CREATE OR REPLACE NETWORK RULE {rule}",
            f"  TYPE = {kind}",
            "  MODE = EGRESS",
            f"  VALUE_LIST = ({', '.join(repr(v) for v in values)});",
        ]
    out.append("")
    return "\n".join(out)


def _secret_sql(ctx: _Context, n: dict[str, str]) -> str:
    return "\n".join(
        [
            _header(ctx),
            "-- Replace the placeholders in a copy, run it once, then delete the copy."
            " Never commit values.",
            f"USE SCHEMA {n['fq']};",
            f"CREATE OR REPLACE SECRET {n['app']}_SAS_CREDENTIALS",
            "  TYPE = PASSWORD",
            "  USERNAME = '<sas-user>'",
            "  PASSWORD = '<sas-password>';",
            "",
        ]
    )


def _streamlit_sql(ctx: _Context, n: dict[str, str]) -> str:
    rules = ", ".join(r for r, _, _ in _rules(ctx, n))
    return "\n".join(
        [
            _header(ctx),
            "-- Run after setup.sql and secret.sql, and after the bundle is on the stage.",
            f"USE SCHEMA {n['fq']};",
            "",
            f"CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION {n['app']}_SAS_ACCESS",
            f"  ALLOWED_NETWORK_RULES = ({rules})",
            f"  ALLOWED_AUTHENTICATION_SECRETS = ({n['secret']})",
            "  ENABLED = TRUE;",
            "",
            f"CREATE STREAMLIT IF NOT EXISTS {n['app']}",
            f"  FROM '@{n['stage']}/app'",
            "  MAIN_FILE = 'streamlit_app.py'",
            "  RUNTIME_NAME = 'SYSTEM$ST_CONTAINER_RUNTIME_PY3_11'",
            f"  COMPUTE_POOL = {n['pool']}",
            f"  QUERY_WAREHOUSE = {n['warehouse']}",
            f"  TITLE = '{n['title']}'",
            "  ARTIFACT_REPOSITORIES = (snowflake.snowpark.pypi_shared_repository)",
            f"  EXTERNAL_ACCESS_INTEGRATIONS = ({n['app']}_SAS_ACCESS)",
            f"  SECRETS = ('sashiny_sas' = {n['secret']});",
            "",
            f"ALTER STREAMLIT {n['app']} ADD LIVE VERSION FROM LAST;",
            "",
        ]
    )


def _guide(ctx: _Context, n: dict[str, str]) -> str:
    lines = [
        "# Deploy to Streamlit in Snowflake",
        "",
        f"Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.5). "
        "Replace every `<...>` placeholder.",
        "",
        "The app runs the SAShiny Streamlit front end on a Streamlit in Snowflake container"
        " runtime. The",
        "runtime cannot install Java, so it reaches SAS Viya over HTTPS only. Packages are"
        " installed from",
        "PyPI through the Snowflake artifact repository"
        " `snowflake.snowpark.pypi_shared_repository`; your",
        "role needs `GRANT DATABASE ROLE SNOWFLAKE.PYPI_REPOSITORY_USER TO ROLE <role>`.",
        "",
        "The app reaches SAS at these host:port pairs; `snowflake/setup.sql` allows them in a"
        " network rule:",
        "",
        *[f"- {e}" for e in _endpoints(ctx)],
        "",
    ]
    if ctx.options.get("private_connectivity"):
        lines += [
            "The SAS profile is reachable only over a private network. Provision a private"
            " endpoint for each",
            "host first (Business Critical edition or higher); `snowflake/setup.sql` creates one",
            "`PRIVATE_HOST_PORT` rule per host.",
            "",
        ]
    lines += [
        "## 1. Create the objects",
        "",
        "```sh",
        "snow sql -f snowflake/setup.sql",
        "```",
        "",
        "## 2. Store the SAS credentials",
        "",
        "Copy `snowflake/secret.sql`, replace the placeholders in the copy, run it, then delete"
        " the copy:",
        "",
        "```sh",
        "snow sql -f <copy-of-secret.sql>",
        "```",
        "",
        "## 3. Upload the app and create it",
        "",
        "```sh",
        f"snow stage copy bundle @{n['stage']}/app --recursive --overwrite",
        "snow sql -f snowflake/streamlit.sql",
        "```",
        "",
        "Open the app in Snowsight under Projects > Streamlit, or with"
        f" `snow streamlit get-url {n['app']}`.",
        "",
    ]
    return "\n".join(lines)


def generate(ctx: _Context) -> dict[str, str]:
    """Write the Streamlit entry point, dependencies, SQL and guide."""
    n = _names(ctx)
    return {
        "bundle/streamlit_app.py": _app_py(ctx, n),
        "bundle/pyproject.toml": _pyproject(ctx),
        "snowflake/setup.sql": _setup_sql(ctx, n),
        "snowflake/secret.sql": _secret_sql(ctx, n),
        "snowflake/streamlit.sql": _streamlit_sql(ctx, n),
        "deploy-streamlit-snowflake.md": _guide(ctx, n),
    }


def _apply(ctx: _Context, result: DeployResult, runner: Runner) -> list[list[str]]:
    n = _names(ctx)
    out = str(result.out_dir)
    conn = ctx.options.get("connection")
    commands = [
        _snow(["sql", "-f", f"{out}/snowflake/setup.sql"], conn),
        _snow(
            ["stage", "copy", f"{out}/bundle", f"@{n['stage']}/app", "--recursive", "--overwrite"],
            conn,
        ),
        _snow(["sql", "-f", f"{out}/snowflake/streamlit.sql"], conn),
    ]
    for cmd in commands:
        status = runner(cmd, {})
        if status != 0:
            raise RuntimeError(f"command failed with exit status {status}: {' '.join(cmd[:3])}")
    return commands


def _doctor(runner: Runner) -> list[str]:
    if not shutil.which("snow"):
        return ["snow (Snowflake CLI) is not on PATH"]
    if runner(["snow", "connection", "test"], {}) != 0:
        return ["snow has no working connection (run snow connection add)"]
    return []


register(
    Target(
        id="streamlit_snowflake",
        label="Streamlit in Snowflake (Python only)",
        languages=("python",),
        options=(
            "language",
            "app_name",
            "database",
            "schema",
            "compute_pool",
            "warehouse",
            "title",
            "private_connectivity",
        ),
        generate=generate,
        private_network_option="private_connectivity",
        needs_java_runtime=False,
        apply=_apply,
        doctor=_doctor,
    )
)
