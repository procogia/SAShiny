"""Amazon ECS (Fargate) + ALB target ``aws_ecs_express`` (spec ``CONTRACT.md`` §6.8.2).

ECS Express Mode (https://docs.aws.amazon.com/AmazonECS/latest/developerguide/express-service-overview.html,
https://docs.aws.amazon.com/AWSCloudFormation/latest/TemplateReference/aws-resource-ecs-expressgatewayservice.html)
does not expose target-group stickiness or the ALB idle timeout, so the template declares the
standard ECS and Elastic Load Balancing resources.
"""

from __future__ import annotations

import shutil

from ..deploy import DeployResult, Runner, Target, _Context, _generate_container, register
from ..errors import DeployError
from .azure import validate_app_name

__all__ = ["generate", "template"]

_MAX_TASKS = 10


def _param(var: str) -> str:
    return "SasUserSecretArn" if var.endswith("USER") else "SasPasswordSecretArn"


def _options(ctx: _Context) -> tuple[str, int]:
    name = validate_app_name(ctx.options.get("app_name", "sashiny-app"))
    count = ctx.options.get("desired_count", 1)
    if isinstance(count, bool) or not isinstance(count, int) or not 1 <= count <= _MAX_TASKS:
        raise DeployError("desired_count must be an integer from 1 to 10")
    return name, count


def _sas_ports(ctx: _Context) -> list[int]:
    ports = {int(e.rsplit(":", 1)[1]) for e in ctx.profile.endpoints}
    return sorted(p for p in ports if p != 443)  # noqa: PLR2004


def template(ctx: _Context) -> str:
    """Return ``infra/template.yaml`` (spec §6.8.2), byte-exact."""
    name, count = _options(ctx)
    port = int(ctx.options.get("port", 8000))
    secrets = ctx.profile.secrets
    extra_ports = _sas_ports(ctx)
    out = [
        f"# Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.2). Do not edit by hand.",
        "# Standard ECS (Fargate) and ALB resources: ECS Express Mode does not expose target-group",
        "# stickiness or the load balancer idle timeout, which Shiny needs.",
        "# Secrets are Secrets Manager ARNs; no secret value is stored in this file.",
        "AWSTemplateFormatVersion: '2010-09-09'",
        f"Description: SAShiny app {name} on Amazon ECS (Fargate) behind an Application Load"
        " Balancer.",
        "",
        "Parameters:",
        "  ImageUri:",
        "    Type: String",
        "    Description: Container image URI in Amazon ECR.",
        "  VpcId:",
        "    Type: AWS::EC2::VPC::Id",
        "    Description: VPC of the subnets.",
        "  PublicSubnetIds:",
        "    Type: List<AWS::EC2::Subnet::Id>",
        "    Description: Subnets of the internet-facing load balancer, in at least two"
        " Availability Zones.",
        "  PrivateSubnetIds:",
        "    Type: List<AWS::EC2::Subnet::Id>",
        "    Description: Subnets of the tasks, with outbound access to SAS through a NAT gateway.",
        "  CertificateArn:",
        "    Type: String",
        "    Description: ACM certificate ARN of the HTTPS listener.",
    ]
    if extra_ports:
        out += [
            "  SasEgressCidr:",
            "    Type: String",
            "    Default: 0.0.0.0/0",
            "    Description: CIDR of the SAS hosts, for SAS ports other than 443.",
        ]
    for var in secrets:
        out += [
            f"  {_param(var)}:",
            "    Type: String",
            f"    Description: Secrets Manager ARN of {var}.",
        ]
    out += [
        "",
        "Resources:",
        "  Cluster:",
        "    Type: AWS::ECS::Cluster",
        "    Properties:",
        f"      ClusterName: {name}",
        "",
        "  LogGroup:",
        "    Type: AWS::Logs::LogGroup",
        "    Properties:",
        f"      LogGroupName: /ecs/{name}",
        "      RetentionInDays: 30",
        "",
        "  ExecutionRole:",
        "    Type: AWS::IAM::Role",
        "    Properties:",
        *_assume_role(),
        "      ManagedPolicyArns:",
        "        - arn:aws:iam::aws:policy/service-role/AmazonECSTaskExecutionRolePolicy",
    ]
    if secrets:
        out += [
            "      Policies:",
            "        - PolicyName: read-sas-secrets",
            "          PolicyDocument:",
            "            Version: '2012-10-17'",
            "            Statement:",
            "              - Effect: Allow",
            "                Action: secretsmanager:GetSecretValue",
            "                Resource:",
            *[f"                  - !Ref {_param(v)}" for v in secrets],
        ]
    out += [
        "",
        "  TaskRole:",
        "    Type: AWS::IAM::Role",
        "    Properties:",
        *_assume_role(),
        "",
        "  LoadBalancerSecurityGroup:",
        "    Type: AWS::EC2::SecurityGroup",
        "    Properties:",
        f"      GroupDescription: {name} load balancer",
        "      VpcId: !Ref VpcId",
        "      SecurityGroupIngress:",
        *_rule(443, "CidrIp: 0.0.0.0/0"),
        "",
        "  ServiceSecurityGroup:",
        "    Type: AWS::EC2::SecurityGroup",
        "    Properties:",
        f"      GroupDescription: {name} tasks",
        "      VpcId: !Ref VpcId",
        "      SecurityGroupIngress:",
        *_rule(port, "SourceSecurityGroupId: !Ref LoadBalancerSecurityGroup"),
        "      SecurityGroupEgress:",
        *_rule(443, "CidrIp: 0.0.0.0/0"),
    ]
    for p in extra_ports:
        out += _rule(p, "CidrIp: !Ref SasEgressCidr")
    out += [
        "",
        "  LoadBalancer:",
        "    Type: AWS::ElasticLoadBalancingV2::LoadBalancer",
        "    Properties:",
        f"      Name: {name}",
        "      Type: application",
        "      Scheme: internet-facing",
        "      Subnets: !Ref PublicSubnetIds",
        "      SecurityGroups:",
        "        - !Ref LoadBalancerSecurityGroup",
        "      LoadBalancerAttributes:",
        "        - Key: idle_timeout.timeout_seconds",
        "          Value: '3600'",
        "",
        "  TargetGroup:",
        "    Type: AWS::ElasticLoadBalancingV2::TargetGroup",
        "    Properties:",
        f"      Name: {name}",
        "      TargetType: ip",
        "      Protocol: HTTP",
        f"      Port: {port}",
        "      VpcId: !Ref VpcId",
        "      HealthCheckPath: /",
        "      Matcher:",
        "        HttpCode: '200'",
        "      TargetGroupAttributes:",
        "        - Key: stickiness.enabled",
        "          Value: 'true'",
        "        - Key: stickiness.type",
        "          Value: lb_cookie",
        "        - Key: stickiness.lb_cookie.duration_seconds",
        "          Value: '86400'",
        "",
        "  HttpsListener:",
        "    Type: AWS::ElasticLoadBalancingV2::Listener",
        "    Properties:",
        "      LoadBalancerArn: !Ref LoadBalancer",
        "      Port: 443",
        "      Protocol: HTTPS",
        "      SslPolicy: ELBSecurityPolicy-TLS13-1-2-2021-06",
        "      Certificates:",
        "        - CertificateArn: !Ref CertificateArn",
        "      DefaultActions:",
        "        - Type: forward",
        "          TargetGroupArn: !Ref TargetGroup",
        "",
        "  TaskDefinition:",
        "    Type: AWS::ECS::TaskDefinition",
        "    Properties:",
        f"      Family: {name}",
        "      RequiresCompatibilities:",
        "        - FARGATE",
        "      NetworkMode: awsvpc",
        "      Cpu: '2048'",
        "      Memory: '4096'",
        "      RuntimePlatform:",
        "        OperatingSystemFamily: LINUX",
        "        CpuArchitecture: X86_64",
        "      ExecutionRoleArn: !GetAtt ExecutionRole.Arn",
        "      TaskRoleArn: !GetAtt TaskRole.Arn",
        "      ContainerDefinitions:",
        "        - Name: app",
        "          Image: !Ref ImageUri",
        "          User: '10001'",
        "          Essential: true",
        "          PortMappings:",
        f"            - ContainerPort: {port}",
        "              Protocol: tcp",
        "          Environment:",
    ]
    for key, value in ctx.profile.env:
        out += [f"            - Name: {key}", f"              Value: '{value}'"]
    if secrets:
        out.append("          Secrets:")
        for var in secrets:
            out += [f"            - Name: {var}", f"              ValueFrom: !Ref {_param(var)}"]
    out += [
        "          LogConfiguration:",
        "            LogDriver: awslogs",
        "            Options:",
        "              awslogs-group: !Ref LogGroup",
        "              awslogs-region: !Ref AWS::Region",
        "              awslogs-stream-prefix: app",
        "",
        "  Service:",
        "    Type: AWS::ECS::Service",
        "    DependsOn: HttpsListener",
        "    Properties:",
        f"      ServiceName: {name}",
        "      Cluster: !Ref Cluster",
        "      LaunchType: FARGATE",
        f"      DesiredCount: {count}",
        "      TaskDefinition: !Ref TaskDefinition",
        "      HealthCheckGracePeriodSeconds: 120",
        "      NetworkConfiguration:",
        "        AwsvpcConfiguration:",
        "          AssignPublicIp: DISABLED",
        "          Subnets: !Ref PrivateSubnetIds",
        "          SecurityGroups:",
        "            - !Ref ServiceSecurityGroup",
        "      LoadBalancers:",
        "        - ContainerName: app",
        f"          ContainerPort: {port}",
        "          TargetGroupArn: !Ref TargetGroup",
        "",
        "Outputs:",
        "  Url:",
        "    Description: App address.",
        "    Value: !Sub 'https://${LoadBalancer.DNSName}'",
        "  LoadBalancerDnsName:",
        "    Description: Point your custom domain at this name.",
        "    Value: !GetAtt LoadBalancer.DNSName",
        "",
    ]
    return "\n".join(out)


def _assume_role() -> list[str]:
    return [
        "      AssumeRolePolicyDocument:",
        "        Version: '2012-10-17'",
        "        Statement:",
        "          - Effect: Allow",
        "            Principal:",
        "              Service: ecs-tasks.amazonaws.com",
        "            Action: sts:AssumeRole",
    ]


def _rule(port: int, source: str) -> list[str]:
    return [
        "        - IpProtocol: tcp",
        f"          FromPort: {port}",
        f"          ToPort: {port}",
        f"          {source}",
    ]


def _guide(ctx: _Context) -> str:
    name, _count = _options(ctx)
    prof = ctx.profile
    registry = "<account>.dkr.ecr.<region>.amazonaws.com"
    image = f"{registry}/{name}:<image-tag>"
    lines = [
        "# Deploy to Amazon ECS (Fargate)",
        "",
        f"Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.2). "
        "Replace every `<...>` placeholder.",
        "",
        "The template uses standard ECS and Elastic Load Balancing resources rather than ECS"
        " Express Mode,",
        "because Express Mode does not expose target-group stickiness or the load balancer idle"
        " timeout,",
        "which Shiny needs.",
        "",
        "The app reaches SAS at these host:port pairs; allow outbound traffic to them:",
        "",
        *[f"- {e}" for e in prof.endpoints],
        "",
        "The tasks run in the private subnets, which reach these endpoints through a NAT gateway.",
        "",
    ]
    if ctx.options.get("private_network"):
        lines += [
            "The SAS profile is reachable only over a private network. Route the private subnets"
            " to it through",
            "a Site-to-Site VPN or a Transit Gateway attachment before deploying.",
            "",
        ]
    step = 1
    if prof.secrets:
        lines += [
            f"## {step}. Store the SAS credentials in Secrets Manager",
            "",
            "```sh",
            "aws secretsmanager create-secret --name sashiny/sas-user --secret-string <sas-user>",
            "aws secretsmanager create-secret --name sashiny/sas-password --secret-string"
            " <sas-password>",
            "```",
            "",
            f"Use the two returned ARNs in step {step + 2}.",
            "",
        ]
        step += 1
    lines += [
        f"## {step}. Build and push the image",
        "",
        "```sh",
        f"aws ecr create-repository --repository-name {name}",
        f"aws ecr get-login-password | docker login --username AWS --password-stdin {registry}",
        f"docker build --platform linux/amd64 -t {image} .",
        f"docker push {image}",
        "```",
        "",
        f"## {step + 1}. Deploy",
        "",
        "```sh",
        f"aws cloudformation deploy --stack-name {name} \\",
        "  --template-file infra/template.yaml --capabilities CAPABILITY_IAM \\",
        f"  --parameter-overrides ImageUri={image} \\",
        "  VpcId=<vpc-id> PublicSubnetIds=<subnet-a>,<subnet-b>"
        " PrivateSubnetIds=<subnet-c>,<subnet-d> \\",
    ]
    if prof.secrets:
        lines += [
            "  CertificateArn=<acm-certificate-arn> \\",
            "  SasUserSecretArn=<sas-user-secret-arn>"
            " SasPasswordSecretArn=<sas-password-secret-arn>",
        ]
    else:
        lines.append("  CertificateArn=<acm-certificate-arn>")
    lines += [
        "```",
        "",
        "The stack output `Url` is the app address. The load balancer keeps idle WebSockets open"
        " for an hour",
        "and uses cookie stickiness, so each browser stays on one task.",
        "",
        "## Custom domain (optional)",
        "",
        "Request or import an ACM certificate for your host name and pass it as `CertificateArn`."
        " Then",
        "create a Route 53 alias record, or a CNAME record at your DNS provider, for the host name"
        " that",
        "points to the stack output `LoadBalancerDnsName`.",
        "",
    ]
    return "\n".join(lines)


def generate(ctx: _Context) -> dict[str, str]:
    """Write the container artifacts plus the CloudFormation template and guide."""
    files = _generate_container(ctx)
    files["infra/template.yaml"] = template(ctx)
    files["deploy-aws.md"] = _guide(ctx)
    return files


def _ids(value: object) -> str:
    if isinstance(value, (list, tuple)):
        return ",".join(str(v) for v in value)
    return str(value)


def _apply(ctx: _Context, result: DeployResult, runner: Runner) -> list[list[str]]:
    opts = ctx.options
    need = ["image_uri", "vpc_id", "public_subnet_ids", "private_subnet_ids", "certificate_arn"]
    if ctx.profile.secrets:
        need += ["sas_user_secret_arn", "sas_password_secret_arn"]
    missing = [k for k in need if not opts.get(k)]
    if missing:
        raise DeployError("apply needs the options " + ", ".join(missing))
    name, _count = _options(ctx)
    out = str(result.out_dir)
    image = str(opts["image_uri"])
    deploy = [
        "aws", "cloudformation", "deploy",
        "--stack-name", str(opts.get("stack_name") or name),
        "--template-file", f"{out}/infra/template.yaml",
        "--capabilities", "CAPABILITY_IAM",
        "--parameter-overrides",
        f"ImageUri={image}",
        f"VpcId={opts['vpc_id']}",
        f"PublicSubnetIds={_ids(opts['public_subnet_ids'])}",
        f"PrivateSubnetIds={_ids(opts['private_subnet_ids'])}",
        f"CertificateArn={opts['certificate_arn']}",
    ]  # fmt: skip
    if ctx.profile.secrets:
        deploy += [
            f"SasUserSecretArn={opts['sas_user_secret_arn']}",
            f"SasPasswordSecretArn={opts['sas_password_secret_arn']}",
        ]
    commands = [
        ["docker", "build", "--platform", "linux/amd64", "-t", image, out],
        ["docker", "push", image],
        deploy,
    ]
    for cmd in commands:
        status = runner(cmd, {})
        if status != 0:
            raise RuntimeError(f"command failed with exit status {status}: {' '.join(cmd[:3])}")
    return commands


def _doctor(runner: Runner) -> list[str]:
    if not shutil.which("aws"):
        return ["aws (AWS CLI) is not on PATH"]
    if runner(["aws", "sts", "get-caller-identity", "--output", "text"], {}) != 0:
        return ["aws has no valid credentials (run aws configure or aws sso login)"]
    if not shutil.which("docker"):
        return ["docker is not on PATH"]
    return []


register(
    Target(
        id="aws_ecs_express",
        label="Amazon ECS (Fargate) with an Application Load Balancer",
        languages=("python", "r"),
        options=("port", "language", "app_name", "desired_count", "private_network"),
        generate=generate,
        apply=_apply,
        doctor=_doctor,
    )
)
