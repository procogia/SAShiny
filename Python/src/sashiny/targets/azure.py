"""Azure Container Apps target (spec ``CONTRACT.md`` §6.8.1).

Bicep reference: https://learn.microsoft.com/en-us/azure/templates/microsoft.app/containerapps
Sticky sessions: https://learn.microsoft.com/en-us/azure/container-apps/sticky-sessions
"""

from __future__ import annotations

import json
import re
import shutil
from typing import Any

from ..deploy import DeployResult, Runner, Target, _Context, _generate_container, register
from ..errors import DeployError

__all__ = ["bicep", "generate", "validate_app_name"]

_APP_NAME = re.compile(r"^[a-z][a-z0-9-]{1,31}$")
_MAX_REPLICAS = 30


def _secret_name(var: str) -> str:
    return var.lower().replace("_", "-")


def _secret_param(var: str) -> str:
    return "sasUserSecretUri" if var.endswith("USER") else "sasPasswordSecretUri"


def validate_app_name(name: object) -> str:
    """Return ``name`` if it is a valid ``app_name`` (spec §6.8.1), else raise ``ValueError``."""
    if not isinstance(name, str) or not _APP_NAME.match(name) or name.endswith("-"):
        raise DeployError(
            "app_name must be 2-32 lowercase letters, digits or '-', starting with a letter"
        )
    return name


def _options(ctx: _Context) -> tuple[str, int, str | None]:
    name = validate_app_name(ctx.options.get("app_name", "sashiny-app"))
    replicas = ctx.options.get("max_replicas", 1)
    if (
        isinstance(replicas, bool)
        or not isinstance(replicas, int)
        or not 1 <= replicas <= _MAX_REPLICAS
    ):
        raise DeployError("max_replicas must be an integer from 1 to 30")
    subnet = ctx.options.get("infrastructure_subnet_id")
    if subnet is not None and (
        not isinstance(subnet, str)
        or not subnet.startswith("/subscriptions/")
        or re.search(r"[\s'\"\\$`]", subnet)
    ):
        raise DeployError("infrastructure_subnet_id must be a subnet resource id")
    return name, replicas, subnet


def bicep(ctx: _Context) -> str:
    """Return ``infra/main.bicep`` (spec §6.8.1), byte-exact."""
    prof = ctx.profile
    secrets = prof.secrets
    out = [
        f"// Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.1). Do not edit by hand.",
        "// Azure Container Apps: external ingress with WebSockets (transport auto) and sticky"
        " sessions.",
        "// Secrets are Key Vault references; no secret value is stored in this file.",
        "",
        "@description('Container App name.')",
        "param appName string",
        "",
        "@description('Port the app listens on.')",
        "param port int",
        "",
        "@description('Maximum replicas (sticky sessions keep each browser on one replica).')",
        "@minValue(1)",
        "@maxValue(30)",
        "param maxReplicas int",
        "",
        "@description('Existing Azure Container Registry that holds the image.')",
        "param acrName string",
        "",
        "@description('Image tag in the registry.')",
        "param imageTag string = 'latest'",
        "",
    ]
    for var in secrets:
        out += [
            f"@description('Key Vault secret URI of {var}.')",
            f"param {_secret_param(var)} string",
            "",
        ]
    out += [
        "@description('Subnet resource id for VNet integration, or empty for none.')",
        "param infrastructureSubnetId string = ''",
        "",
        "param location string = resourceGroup().location",
        "",
        "resource acr 'Microsoft.ContainerRegistry/registries@2023-07-01' existing = {",
        "  name: acrName",
        "}",
        "",
        "resource identity 'Microsoft.ManagedIdentity/userAssignedIdentities@2023-01-31' = {",
        "  name: '${appName}-id'",
        "  location: location",
        "}",
        "",
        "resource acrPull 'Microsoft.Authorization/roleAssignments@2022-04-01' = {",
        "  name: guid(acr.id, identity.id, 'acrpull')",
        "  scope: acr",
        "  properties: {",
        "    principalId: identity.properties.principalId",
        "    principalType: 'ServicePrincipal'",
        "    roleDefinitionId: subscriptionResourceId('Microsoft.Authorization/roleDefinitions',"
        " '7f951dda-4ed3-4680-a7ca-43fe172d538d')",
        "  }",
        "}",
        "",
        "resource logs 'Microsoft.OperationalInsights/workspaces@2023-09-01' = {",
        "  name: '${appName}-logs'",
        "  location: location",
        "  properties: {",
        "    sku: {",
        "      name: 'PerGB2018'",
        "    }",
        "    retentionInDays: 30",
        "  }",
        "}",
        "",
        "resource env 'Microsoft.App/managedEnvironments@2025-07-01' = {",
        "  name: '${appName}-env'",
        "  location: location",
        "  properties: {",
        "    appLogsConfiguration: {",
        "      destination: 'log-analytics'",
        "      logAnalyticsConfiguration: {",
        "        customerId: logs.properties.customerId",
        "        sharedKey: logs.listKeys().primarySharedKey",
        "      }",
        "    }",
        "    vnetConfiguration: empty(infrastructureSubnetId) ? null : {",
        "      infrastructureSubnetId: infrastructureSubnetId",
        "    }",
        "  }",
        "}",
        "",
        "resource app 'Microsoft.App/containerApps@2025-07-01' = {",
        "  name: appName",
        "  location: location",
        "  identity: {",
        "    type: 'UserAssigned'",
        "    userAssignedIdentities: {",
        "      '${identity.id}': {}",
        "    }",
        "  }",
        "  dependsOn: [",
        "    acrPull",
        "  ]",
        "  properties: {",
        "    managedEnvironmentId: env.id",
        "    configuration: {",
        "      activeRevisionsMode: 'Single'",
        "      ingress: {",
        "        external: true",
        "        targetPort: port",
        "        transport: 'auto'",
        "        stickySessions: {",
        "          affinity: 'sticky'",
        "        }",
        "      }",
        "      registries: [",
        "        {",
        "          server: acr.properties.loginServer",
        "          identity: identity.id",
        "        }",
        "      ]",
    ]
    if secrets:
        out.append("      secrets: [")
        for var in secrets:
            out += [
                "        {",
                f"          name: '{_secret_name(var)}'",
                f"          keyVaultUrl: {_secret_param(var)}",
                "          identity: identity.id",
                "        }",
            ]
        out.append("      ]")
    out += [
        "    }",
        "    template: {",
        "      containers: [",
        "        {",
        "          name: 'app'",
        "          image: '${acr.properties.loginServer}/${appName}:${imageTag}'",
        "          resources: {",
        "            cpu: json('2.0')",
        "            memory: '4Gi'",
        "          }",
        "          env: [",
    ]
    for name, value in prof.env:
        out += [
            "            {",
            f"              name: '{name}'",
            f"              value: '{value}'",
            "            }",
        ]
    for var in secrets:
        out += [
            "            {",
            f"              name: '{var}'",
            f"              secretRef: '{_secret_name(var)}'",
            "            }",
        ]
    out += [
        "          ]",
        "          probes: [",
        "            {",
        "              type: 'Readiness'",
        "              httpGet: {",
        "                path: '/'",
        "                port: port",
        "              }",
        "              periodSeconds: 10",
        "            }",
        "          ]",
        "        }",
        "      ]",
        "      scale: {",
        "        minReplicas: 1",
        "        maxReplicas: maxReplicas",
        "      }",
        "    }",
        "  }",
        "}",
        "",
        "output url string = 'https://${app.properties.configuration.ingress.fqdn}'",
        "",
    ]
    return "\n".join(out)


def _parameters(name: str, port: int, replicas: int, subnet: str | None) -> str:
    params: dict[str, Any] = {
        "appName": {"value": name},
        "port": {"value": port},
        "maxReplicas": {"value": replicas},
    }
    if subnet:
        params["infrastructureSubnetId"] = {"value": subnet}
    doc = {
        "$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentParameters.json#",
        "contentVersion": "1.0.0.0",
        "parameters": params,
    }
    return json.dumps(doc, indent=2) + "\n"


def _guide(ctx: _Context, name: str, subnet: str | None) -> str:
    prof = ctx.profile
    lines = [
        "# Deploy to Azure Container Apps",
        "",
        f"Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.1). "
        "Replace every `<...>` placeholder.",
        "",
        "The app reaches SAS at these host:port pairs; allow outbound traffic to them:",
        "",
        *[f"- {e}" for e in prof.endpoints],
        "",
    ]
    if subnet:
        lines += [
            f"The environment is integrated with the subnet `{subnet}`,",
            "which must route to the SAS host.",
            "",
        ]
    if prof.secrets:
        lines += [
            "## 1. Store the SAS credentials in Key Vault",
            "",
            "```sh",
            "az keyvault secret set --vault-name <key-vault> --name sashiny-sas-user "
            "--value <sas-user>",
            "az keyvault secret set --vault-name <key-vault> --name sashiny-sas-password "
            "--value <sas-password>",
            "```",
            "",
            f"Grant the app's managed identity (`{name}-id`, created by the template) the",
            '"Key Vault Secrets User" role on the vault after the first deployment, then restart'
            " the revision.",
            "",
        ]
    secret_args = (
        " \\\n  sasUserSecretUri=https://<key-vault>.vault.azure.net/secrets/sashiny-sas-user \\\n"
        "  sasPasswordSecretUri=https://<key-vault>.vault.azure.net/secrets/sashiny-sas-password"
        if prof.secrets
        else ""
    )
    lines += [
        "## 2. Build the image in your registry",
        "",
        "```sh",
        f"az acr build --registry <acr-name> --image {name}:<image-tag> .",
        "```",
        "",
        "## 3. Deploy",
        "",
        "```sh",
        "az deployment group create --resource-group <resource-group> \\",
        "  --template-file infra/main.bicep --parameters @infra/main.parameters.json \\",
        "  acrName=<acr-name> imageTag=<image-tag>" + secret_args,
        "```",
        "",
        "The deployment output `url` is the app address. Ingress uses WebSockets (transport auto)"
        " and",
        "sticky sessions, so each browser stays on one replica.",
        "",
        "## Custom domain (optional)",
        "",
        "Add a CNAME record for your host name pointing to the app's FQDN, and a TXT record",
        "`asuid.<host>` with the environment's custom domain verification id, then run",
        "`az containerapp hostname add` and `az containerapp hostname bind --validation-method"
        " CNAME`.",
        "",
    ]
    return "\n".join(lines)


def generate(ctx: _Context) -> dict[str, str]:
    """Write the container artifacts plus the Bicep template and guide."""
    name, replicas, subnet = _options(ctx)
    port = int(ctx.options.get("port", 8000))
    files = _generate_container(ctx)
    files["infra/main.bicep"] = bicep(ctx)
    files["infra/main.parameters.json"] = _parameters(name, port, replicas, subnet)
    files["deploy-azure.md"] = _guide(ctx, name, subnet)
    return files


def _apply(ctx: _Context, result: DeployResult, runner: Runner) -> list[list[str]]:
    opts = ctx.options
    missing = [k for k in ("resource_group", "acr_name") if not opts.get(k)]
    if ctx.profile.secrets:
        missing += [
            k for k in ("sas_user_secret_uri", "sas_password_secret_uri") if not opts.get(k)
        ]
    if missing:
        raise DeployError("apply needs the options " + ", ".join(missing))
    name, _replicas, _subnet = _options(ctx)
    tag = str(opts.get("image_tag", "latest"))
    out = str(result.out_dir)
    build = [
        "az",
        "acr",
        "build",
        "--registry",
        str(opts["acr_name"]),
        "--image",
        f"{name}:{tag}",
        out,
    ]
    create = [
        "az", "deployment", "group", "create",
        "--resource-group", str(opts["resource_group"]),
        "--template-file", f"{out}/infra/main.bicep",
        "--parameters", f"@{out}/infra/main.parameters.json",
        f"acrName={opts['acr_name']}", f"imageTag={tag}",
    ]  # fmt: skip
    if ctx.profile.secrets:
        create += [
            f"sasUserSecretUri={opts['sas_user_secret_uri']}",
            f"sasPasswordSecretUri={opts['sas_password_secret_uri']}",
        ]
    commands = [build, create]
    for cmd in commands:
        status = runner(cmd, {})
        if status != 0:
            raise RuntimeError(f"command failed with exit status {status}: {' '.join(cmd[:4])}")
    return commands


def _doctor(runner: Runner) -> list[str]:
    if not shutil.which("az"):
        return ["az (Azure CLI) is not on PATH"]
    if runner(["az", "account", "show", "--output", "none"], {}) != 0:
        return ["az is not logged in (run az login)"]
    return []


register(
    Target(
        id="azure_container_apps",
        label="Azure Container Apps",
        languages=("python", "r"),
        options=("port", "language", "app_name", "max_replicas", "infrastructure_subnet_id"),
        generate=generate,
        private_network_option="infrastructure_subnet_id",
        apply=_apply,
        doctor=_doctor,
    )
)
