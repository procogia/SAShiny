"""Databricks Apps target ``databricks_apps`` (spec ``CONTRACT.md`` §6.8.6).

app.yaml: https://docs.databricks.com/aws/en/dev-tools/databricks-apps/app-runtime
Environment (Python 3.11 / Node.js, Ubuntu 22.04; no system packages):
https://docs.databricks.com/aws/en/dev-tools/databricks-apps/system-env
Secrets: https://docs.databricks.com/aws/en/dev-tools/databricks-apps/secrets
Deploy: https://docs.databricks.com/aws/en/dev-tools/databricks-apps/deploy

Shiny for R is not a supported framework and Java cannot be installed, so the
target accepts Python apps on http (Viya) profiles only.
"""

from __future__ import annotations

import json
import re
import shutil

from ..deploy import DeployResult, Runner, Target, _Context, register
from ..errors import DeployError

__all__ = ["app_yaml", "generate"]

_APP_NAME = re.compile(r"^[a-z][a-z0-9-]{0,28}[a-z0-9]$")
_SCOPE = re.compile(r"^[A-Za-z0-9_.-]{1,128}$")
_KEYS = {"SASHINY_SAS_USER": "sas-user", "SASHINY_SAS_PASSWORD": "sas-password"}


def _options(ctx: _Context) -> tuple[str, str]:
    if ctx.profile.method != "http":
        raise DeployError("target databricks_apps supports only http (Viya) profiles")
    name = ctx.options.get("app_name", "sashiny-app")
    if not isinstance(name, str) or not _APP_NAME.match(name):
        raise DeployError(
            "app_name must be 2-30 lowercase letters, digits or '-', starting with a letter"
        )
    scope = ctx.options.get("secret_scope", "sashiny")
    if not isinstance(scope, str) or not _SCOPE.match(scope):
        raise DeployError("secret_scope must be 1-128 letters, digits, '_', '-' or '.'")
    return name, scope


def _header(ctx: _Context) -> str:
    return f"# Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.6). Do not edit by hand."


def app_yaml(ctx: _Context) -> str:
    """Return ``bundle/app.yaml`` (spec §6.8.6), byte-exact."""
    out = [
        _header(ctx),
        'command: ["shiny", "run", "app.py", "--host", "0.0.0.0", "--port",'
        ' "$DATABRICKS_APP_PORT"]',
        "env:",
    ]
    for name, value in ctx.profile.env:
        out += [f'  - name: "{name}"', f'    value: "{value}"']
    for var in ctx.profile.secrets:
        out += [f'  - name: "{var}"', f'    valueFrom: "{_KEYS[var]}"']
    out.append("")
    return "\n".join(out)


def _app_json(ctx: _Context, name: str, scope: str) -> str:
    resources = [
        {
            "name": key,
            "secret": {"scope": scope, "key": key, "permission": "READ"},
        }
        for key in (_KEYS[v] for v in ctx.profile.secrets)
    ]
    doc = {"name": name, "description": "SAShiny app", "resources": resources}
    return json.dumps(doc, indent=2) + "\n"


def _guide(ctx: _Context, name: str, scope: str) -> str:
    lines = [
        "# Deploy to Databricks Apps",
        "",
        f"Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.6). "
        "Replace every `<...>` placeholder.",
        "",
        "The app runs Shiny for Python on the Databricks Apps runtime. The runtime cannot install"
        " Java, so it",
        "reaches SAS Viya over HTTPS only. The workspace's serverless egress must allow these"
        " host:port",
        "pairs, and `pypi.org` and `files.pythonhosted.org` for the app build:",
        "",
        *[f"- {e}" for e in ctx.profile.endpoints],
        "",
    ]
    if ctx.options.get("private_connectivity"):
        lines += [
            "The SAS profile is reachable only over a private network. Attach a network"
            " connectivity",
            "configuration with a private endpoint rule for each host to the workspace first.",
            "",
        ]
    path = f"/Workspace/Users/<user>/{name}"
    lines += [
        "## 1. Store the SAS credentials",
        "",
        "```sh",
        f"databricks secrets create-scope {scope}",
        f"databricks secrets put-secret {scope} sas-user",
        f"databricks secrets put-secret {scope} sas-password",
        "```",
        "",
        "The CLI prompts for each value; never pass a value on the command line.",
        "",
        "## 2. Create the app",
        "",
        "```sh",
        "databricks apps create --json @databricks/app.json",
        "```",
        "",
        "## 3. Upload and deploy",
        "",
        "```sh",
        f"databricks sync bundle {path}",
        f"databricks apps deploy {name} --source-code-path {path}",
        "```",
        "",
        "## 4. Share the app",
        "",
        "```sh",
        f'databricks apps update-permissions {name} --json \'{{"access_control_list":'
        ' [{"group_name": "<group>", "permission_level": "CAN_USE"}]}\'',
        "```",
        "",
    ]
    return "\n".join(lines)


def generate(ctx: _Context) -> dict[str, str]:
    """Write app.yaml, requirements.txt, the apps create JSON and the guide."""
    name, scope = _options(ctx)
    return {
        "bundle/app.yaml": app_yaml(ctx),
        "bundle/requirements.txt": f"{_header(ctx)}\n"
        f"sashiny[shiny,saspy,upload,plotnine]=={ctx.version}\n",
        "databricks/app.json": _app_json(ctx, name, scope),
        "deploy-databricks.md": _guide(ctx, name, scope),
    }


def _databricks(args: list[str], profile: object) -> list[str]:
    cmd = ["databricks", *args]
    if profile:
        cmd += ["--profile", str(profile)]
    return cmd


def _apply(ctx: _Context, result: DeployResult, runner: Runner) -> list[list[str]]:
    opts = ctx.options
    path = opts.get("source_code_path")
    if not isinstance(path, str) or not path.startswith("/Workspace/"):
        raise DeployError("apply needs the option source_code_path (a /Workspace/... path)")
    name, _scope = _options(ctx)
    out = str(result.out_dir)
    prof = opts.get("databricks_profile")
    commands = []
    if opts.get("create"):
        commands.append(
            _databricks(["apps", "create", "--json", f"@{out}/databricks/app.json"], prof)
        )
    commands += [
        _databricks(["sync", f"{out}/bundle", path], prof),
        _databricks(["apps", "deploy", name, "--source-code-path", path], prof),
    ]
    for cmd in commands:
        status = runner(cmd, {})
        if status != 0:
            raise RuntimeError(f"command failed with exit status {status}: {' '.join(cmd[:3])}")
    return commands


def _doctor(runner: Runner) -> list[str]:
    if not shutil.which("databricks"):
        return ["databricks (Databricks CLI) is not on PATH"]
    if runner(["databricks", "current-user", "me"], {}) != 0:
        return ["databricks has no configured profile (run databricks auth login)"]
    return []


register(
    Target(
        id="databricks_apps",
        label="Databricks Apps (Python only)",
        languages=("python",),
        options=("language", "app_name", "secret_scope", "private_connectivity"),
        generate=generate,
        private_network_option="private_connectivity",
        needs_java_runtime=False,
        apply=_apply,
        doctor=_doctor,
    )
)
