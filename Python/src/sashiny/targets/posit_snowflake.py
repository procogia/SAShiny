"""Posit Connect in the Posit Team Native App: target ``posit_snowflake`` (spec §6.8.4).

Egress: https://docs.posit.co/partnerships/snowflake/posit-team/networking/egress.html
Publishing: https://docs.posit.co/partnerships/snowflake/posit-team/connect/publish-outside-snowflake.html

Publishing reuses :func:`sashiny.publish.publish` (spec §6.7); nothing is reimplemented here.
"""

from __future__ import annotations

import importlib.util
import os
from collections.abc import Sequence
from typing import Any

from ..deploy import DeployResult, Runner, Target, _Context, register
from ..errors import DeployError
from .snowflake import _ident

__all__ = ["egress_sql", "generate"]


def _application(ctx: _Context) -> str:
    return str(_ident(ctx.options, "application", "POSIT_TEAM"))


def egress_sql(ctx: _Context) -> str:
    """Return ``snowflake/egress.sql`` (spec §6.8.4), byte-exact."""
    app = _application(ctx)
    schema = f"{app}_APP_DATA.CONFIGURATION"
    integration = f"{app}_CONNECT_EGRESS_EXTERNAL_ACCESS"
    private = bool(ctx.options.get("private_connectivity"))
    out = [
        f"-- Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.4). Do not edit by hand.",
        f"-- Lets Posit Connect in the Posit Team Native App {app} reach SAS.",
        "-- Run as ACCOUNTADMIN or the owner of the integration.",
    ]
    if private:
        out.append(
            "-- Provision a private endpoint for each host first"
            " (SYSTEM$PROVISION_PRIVATELINK_ENDPOINT)."
        )
    out += [
        "",
        "-- Note the rules in ALLOWED_NETWORK_RULES; SET replaces the list, so keep every rule"
        " you need.",
        f"DESCRIBE EXTERNAL ACCESS INTEGRATION {integration};",
        "",
    ]
    endpoints = ctx.profile.endpoints
    if private:
        rules = [(f"{app}_SASHINY_SAS_PRIVATE_{i}", [e]) for i, e in enumerate(endpoints, 1)]
        kind = "PRIVATE_HOST_PORT"
    else:
        rules = [(f"{app}_SASHINY_SAS_EGRESS", list(endpoints))]
        kind = "HOST_PORT"
    for rule, values in rules:
        out += [
            f"CREATE OR REPLACE NETWORK RULE {schema}.{rule}",
            f"  TYPE = {kind}",
            "  MODE = EGRESS",
            f"  VALUE_LIST = ({', '.join(repr(v) for v in values)});",
            "",
        ]
    allowed = [f"{schema}.{app}_CONNECT_EGRESS_NETWORK_RULE"] + [f"{schema}.{r}" for r, _ in rules]
    out += [
        f"ALTER EXTERNAL ACCESS INTEGRATION {integration}",
        "  SET ALLOWED_NETWORK_RULES = (",
        ",\n".join(f"    {a}" for a in allowed) + ")",
        "  ENABLED = TRUE;",
        "",
    ]
    return "\n".join(out)


def _guide(ctx: _Context) -> str:
    prof = ctx.profile
    lines = [
        "# Deploy to Posit Connect in the Posit Team Native App (Snowflake)",
        "",
        f"Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.4). "
        "Replace every `<...>` placeholder.",
        "",
        "Posit manages the runtime: the app is published as ordinary Posit Connect content. To"
        " run your own",
        "container in Snowpark Container Services instead, use the `snowflake_spcs` target.",
        "",
        "The app reaches SAS at these host:port pairs; `snowflake/egress.sql` allows them for"
        " Connect:",
        "",
        *[f"- {e}" for e in prof.endpoints],
        "",
    ]
    if ctx.options.get("private_connectivity"):
        lines += [
            "The SAS profile is reachable only over a private network. `snowflake/egress.sql`"
            " creates one",
            "`PRIVATE_HOST_PORT` rule per host; provision a private endpoint for each host first"
            " (Business",
            "Critical edition or higher).",
            "",
        ]
    if prof.needs_java:
        lines += [
            "The profile uses IOM, which needs Java 17 in the Connect runtime image. Check this"
            " with your Posit",
            "Team administrator.",
            "",
        ]
    lines += [
        "## 1. Allow egress to SAS",
        "",
        "Run `snowflake/egress.sql` in Snowsight, or with `snow sql -f snowflake/egress.sql`.",
        "",
        "## 2. Register the Connect server",
        "",
    ]
    if ctx.language == "python":
        lines += [
            "Provision a Connect API key, then register the server (rsconnect-python 1.28 or"
            " newer):",
            "",
            "```sh",
            'pip install "rsconnect-python[snowflake]"',
            'rsconnect add --server "https://<connect-url>" --name spcs \\',
            "  --api-key <connect-api-key> --snowflake-connection-name <snowflake-connection>",
            "```",
            "",
        ]
    else:
        lines += [
            "Provision a Connect API key, then register the server (rsconnect 1.6.1 or newer):",
            "",
            "```r",
            'install.packages("rsconnect")',
            'rsconnect::addServer("https://<connect-url>", name = "spcs",',
            '  snowflakeConnectionName = "<snowflake-connection>")',
            'rsconnect::connectSPCSUser(server = "spcs", apiKey = "<connect-api-key>",',
            '  snowflakeConnectionName = "<snowflake-connection>")',
            "```",
            "",
        ]
    lines += ["## 3. Publish", ""]
    if prof.secrets:
        lines.append(
            "Set `SASHINY_SAS_USER` and `SASHINY_SAS_PASSWORD` in your session, then publish:"
        )
    else:
        lines.append("Publish:")
    lines.append("")
    if ctx.language == "python":
        lines += [
            "```python",
            "from sashiny.deploy import deploy",
            'deploy("<app-dir>", "posit_snowflake", profile=<profile>, license_ack=True,'
            ' apply=True, server="spcs")',
            "```",
        ]
    else:
        lines += [
            "```r",
            'SAShiny::sas_deploy("<app-dir>", "posit_snowflake", profile = <profile>,'
            " license_ack = TRUE,",
            '  apply = TRUE, server = "spcs")',
            "```",
        ]
    lines += [
        "",
        "Connect stores these environment variables for the content:",
        "",
        *[f"- {k}={v}" for k, v in prof.env],
        *[f"- {s} (secret)" for s in prof.secrets],
        "",
    ]
    return "\n".join(lines)


def generate(ctx: _Context) -> dict[str, str]:
    """Write the egress SQL and the guide (the bundle is written by the core)."""
    _application(ctx)
    return {
        "snowflake/egress.sql": egress_sql(ctx),
        "deploy-posit-snowflake.md": _guide(ctx),
    }


def _apply(ctx: _Context, result: DeployResult, runner: Runner) -> list[list[str]]:
    from ..publish import publish  # noqa: PLC0415 - optional dependency path

    if ctx.language != "python":
        raise DeployError("apply for an R app must run in R (SAShiny::sas_deploy)")
    opts: dict[str, Any] = ctx.options
    server = opts.get("server")
    if not server and not (os.environ.get("CONNECT_SERVER") and os.environ.get("CONNECT_API_KEY")):
        raise DeployError(
            "apply needs the option server or the environment variables CONNECT_SERVER and "
            "CONNECT_API_KEY"
        )
    commands: list[list[str]] = []

    def rsconnect(args: Sequence[str], env: dict[str, str]) -> None:
        cmd = ["rsconnect", *args]
        commands.append(cmd)
        status = runner(cmd, env)
        if status != 0:
            raise RuntimeError(f"command failed with exit status {status}: rsconnect deploy")

    names = [k for k, _ in ctx.profile.env]
    saved = {k: os.environ.get(k) for k in names}
    os.environ.update(dict(ctx.profile.env))
    try:
        publish(
            result.out_dir / "bundle",
            title=opts.get("title"),
            name=str(server) if server else None,
            sas_credentials="env" if ctx.profile.secrets else "server",
            license_ack=True,
            env_vars=names,
            runner=rsconnect,
        )
    finally:
        for key, value in saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value
    return commands


def _doctor(runner: Runner) -> list[str]:
    problems = []
    if importlib.util.find_spec("rsconnect") is None:
        problems.append('rsconnect-python is not installed (pip install "sashiny[connect]")')
    missing = [v for v in ("CONNECT_SERVER", "CONNECT_API_KEY") if not os.environ.get(v)]
    if missing:
        problems.append(f"{' and '.join(missing)} not set; or pass server")
    return problems


register(
    Target(
        id="posit_snowflake",
        label="Posit Connect in the Posit Team Native App (Snowflake)",
        languages=("python", "r"),
        options=("language", "application", "private_connectivity", "title", "server"),
        generate=generate,
        private_network_option="private_connectivity",
        apply=_apply,
        doctor=_doctor,
    )
)
