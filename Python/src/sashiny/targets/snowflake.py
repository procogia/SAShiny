"""Snowpark Container Services target ``snowflake_spcs`` (spec ``CONTRACT.md`` §6.8.3).

Specification: https://docs.snowflake.com/en/developer-guide/snowpark-container-services/specification-reference
Ingress (WebSockets, 90 s idle timeout): https://docs.snowflake.com/en/developer-guide/snowpark-container-services/service-network-communications
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass

from ..deploy import DeployResult, Runner, Target, _Context, _generate_container, register
from ..errors import DeployError

__all__ = ["generate", "service_spec"]

_IDENT = re.compile(r"^[A-Z][A-Z0-9_]{0,62}$")
_MAX_INSTANCES = 10
_KEYS = {"SASHINY_SAS_USER": "username", "SASHINY_SAS_PASSWORD": "password"}


@dataclass(frozen=True)
class _Names:
    service: str
    database: str
    schema: str
    pool: str
    family: str
    instances: int
    public: bool
    grant_role: str | None

    @property
    def image(self) -> str:
        return self.service.lower().replace("_", "-")

    @property
    def fq_schema(self) -> str:
        return f"{self.database}.{self.schema}"


def _ident(options: dict[str, object], key: str, default: str | None) -> str | None:
    value = options.get(key, default)
    if value is None:
        return None
    if not isinstance(value, str) or not _IDENT.match(value):
        raise DeployError(
            f"{key} must be 1-63 uppercase letters, digits or '_', starting with a letter"
        )
    return value


def _names(ctx: _Context) -> _Names:
    o = ctx.options
    instances = o.get("instances", 1)
    if (
        isinstance(instances, bool)
        or not isinstance(instances, int)
        or not 1 <= instances <= _MAX_INSTANCES
    ):
        raise DeployError("instances must be an integer from 1 to 10")
    public = o.get("public", True)
    if not isinstance(public, bool):
        raise DeployError("public must be TRUE or FALSE")
    return _Names(
        service=str(_ident(o, "service_name", "SASHINY_APP")),
        database=str(_ident(o, "database", "SASHINY_DB")),
        schema=str(_ident(o, "schema", "APP")),
        pool=str(_ident(o, "compute_pool", "SASHINY_POOL")),
        family=str(_ident(o, "instance_family", "CPU_X64_S")),
        instances=instances,
        public=public,
        grant_role=_ident(o, "grant_role", None),
    )


def _header(ctx: _Context, mark: str) -> str:
    return f"{mark} Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.3). Do not edit by hand."


def service_spec(ctx: _Context) -> str:
    """Return the service specification body (without the comment line)."""
    n = _names(ctx)
    port = int(ctx.options.get("port", 8000))
    image = f"/{n.database}/{n.schema}/sashiny_repo/{n.image}:latest".lower()
    out = [
        "spec:",
        "  containers:",
        "    - name: app",
        f"      image: {image}",
        "      env:",
        *[f"        {k}: '{v}'" for k, v in ctx.profile.env],
    ]
    if ctx.profile.secrets:
        out.append("      secrets:")
        for var in ctx.profile.secrets:
            out += [
                "        - snowflakeSecret:",
                f"            objectName: {n.service}_SAS_CREDENTIALS",
                f"          envVarName: {var}",
                f"          secretKeyRef: {_KEYS[var]}",
            ]
    out += [
        "      readinessProbe:",
        f"        port: {port}",
        "        path: /",
        "  endpoints:",
        "    - name: app",
        f"      port: {port}",
        f"      public: {'true' if n.public else 'false'}",
        "",
    ]
    return "\n".join(out)


def _endpoints(ctx: _Context) -> list[str]:
    """Return the profile's endpoints that have a single port (spec §6.8).

    Port ranges are left out until Snowflake network rules are verified to accept them (#188).
    """
    return [e for e in ctx.profile.endpoints if "-" not in e.rsplit(":", 1)[1]]


def _setup_sql(ctx: _Context, n: _Names) -> str:
    rules = ", ".join(f"'{e}'" for e in _endpoints(ctx))
    return "\n".join(
        [
            _header(ctx, "--"),
            "-- Run with a role that can create databases, compute pools and integrations.",
            f"CREATE DATABASE IF NOT EXISTS {n.database};",
            f"CREATE SCHEMA IF NOT EXISTS {n.fq_schema};",
            f"USE SCHEMA {n.fq_schema};",
            "",
            "CREATE IMAGE REPOSITORY IF NOT EXISTS SASHINY_REPO;",
            "",
            f"CREATE COMPUTE POOL IF NOT EXISTS {n.pool}",
            f"  MIN_NODES = {n.instances}",
            f"  MAX_NODES = {n.instances}",
            f"  INSTANCE_FAMILY = {n.family};",
            "",
            f"CREATE OR REPLACE NETWORK RULE {n.service}_SAS_EGRESS",
            "  TYPE = HOST_PORT",
            "  MODE = EGRESS",
            f"  VALUE_LIST = ({rules});",
            "",
            f"CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION {n.service}_SAS_ACCESS",
            f"  ALLOWED_NETWORK_RULES = ({n.service}_SAS_EGRESS)",
            "  ENABLED = TRUE;",
            "",
            f"SHOW IMAGE REPOSITORIES IN SCHEMA {n.fq_schema};",
            "",
        ]
    )


def _secret_sql(ctx: _Context, n: _Names) -> str:
    return "\n".join(
        [
            _header(ctx, "--"),
            "-- Replace the placeholders in a copy, run it once, then delete the copy."
            " Never commit values.",
            f"USE SCHEMA {n.fq_schema};",
            f"CREATE OR REPLACE SECRET {n.service}_SAS_CREDENTIALS",
            "  TYPE = PASSWORD",
            "  USERNAME = '<sas-user>'",
            "  PASSWORD = '<sas-password>';",
            "",
        ]
    )


def _service_sql(ctx: _Context, n: _Names) -> str:
    out = [
        _header(ctx, "--"),
        f"USE SCHEMA {n.fq_schema};",
        f"CREATE SERVICE IF NOT EXISTS {n.service}",
        f"  IN COMPUTE POOL {n.pool}",
        f"  MIN_INSTANCES = {n.instances}",
        f"  MAX_INSTANCES = {n.instances}",
        f"  EXTERNAL_ACCESS_INTEGRATIONS = ({n.service}_SAS_ACCESS)",
        "  FROM SPECIFICATION $$",
        service_spec(ctx) + "$$;",
    ]
    if n.grant_role:
        out.append(f"GRANT SERVICE ROLE {n.service}!ALL_ENDPOINTS_USAGE TO ROLE {n.grant_role};")
    out += [f"SHOW ENDPOINTS IN SERVICE {n.service};", ""]
    return "\n".join(out)


def _guide(ctx: _Context, n: _Names) -> str:
    prof = ctx.profile
    lines = [
        "# Deploy to Snowflake (Snowpark Container Services)",
        "",
        f"Generated by SAShiny {ctx.version} (CONTRACT.md 6.8.3). "
        "Replace every `<...>` placeholder.",
        "",
        "The app reaches SAS at these host:port pairs; `spcs/setup.sql` allows them in a network"
        " rule:",
        "",
        *[f"- {e}" for e in _endpoints(ctx)],
        "",
    ]
    if ctx.options.get("private_connectivity"):
        lines += [
            "The SAS profile is reachable only over a private network. Configure private"
            " connectivity from",
            "Snowflake to it (for example AWS PrivateLink or Azure Private Link) before deploying.",
            "",
        ]
    lines += [
        "The public endpoint is reached through Snowflake sign-in. Ingress supports WebSockets"
        " and closes a",
        "connection after 90 seconds without traffic; Shiny's WebSocket heartbeat keeps it open.",
        "",
    ]
    if n.instances > 1:
        lines += [
            f"Warning: the service runs {n.instances} instances. Snowflake does not document"
            " session affinity between",
            "instances, so a browser session may move to another instance and lose its state."
            " Use 1 instance",
            "unless you have verified affinity for your account.",
            "",
        ]
    step = 1
    lines += [
        f"## {step}. Create the objects",
        "",
        "```sh",
        "snow sql -f spcs/setup.sql",
        "```",
        "",
        "The last statement shows the image repository; note its `repository_url`.",
        "",
    ]
    if prof.secrets:
        step += 1
        lines += [
            f"## {step}. Store the SAS credentials",
            "",
            "Copy `spcs/secret.sql`, replace the placeholders in the copy, run it, then delete"
            " the copy:",
            "",
            "```sh",
            "snow sql -f <copy-of-secret.sql>",
            "```",
            "",
        ]
    lines += [
        f"## {step + 1}. Build and push the image",
        "",
        "```sh",
        "snow spcs image-registry login",
        f"docker build --platform linux/amd64 -t <repository_url>/{n.image}:latest .",
        f"docker push <repository_url>/{n.image}:latest",
        "```",
        "",
        f"## {step + 2}. Create the service",
        "",
        "```sh",
        "snow sql -f spcs/service.sql",
        "```",
        "",
    ]
    if n.grant_role:
        lines += [
            "The last statement shows the endpoint `ingress_url`, the app address. Users need"
            " the role",
            f"`{n.grant_role}`, which is granted the endpoint.",
            "",
        ]
    else:
        lines += ["The last statement shows the endpoint `ingress_url`, the app address.", ""]
    return "\n".join(lines)


def generate(ctx: _Context) -> dict[str, str]:
    """Write the container artifacts plus the SPCS specification, SQL and guide."""
    n = _names(ctx)
    files = _generate_container(ctx)
    files["spcs/service-spec.yaml"] = _header(ctx, "#") + "\n" + service_spec(ctx)
    files["spcs/setup.sql"] = _setup_sql(ctx, n)
    if ctx.profile.secrets:
        files["spcs/secret.sql"] = _secret_sql(ctx, n)
    files["spcs/service.sql"] = _service_sql(ctx, n)
    files["deploy-snowflake-spcs.md"] = _guide(ctx, n)
    return files


def _snow(args: list[str], connection: object) -> list[str]:
    cmd = ["snow", *args]
    if connection:
        cmd += ["--connection", str(connection)]
    return cmd


def _apply(ctx: _Context, result: DeployResult, runner: Runner) -> list[list[str]]:
    opts = ctx.options
    if not opts.get("repository_url"):
        raise DeployError("apply needs the options repository_url")
    n = _names(ctx)
    out = str(result.out_dir)
    image = f"{str(opts['repository_url']).rstrip('/')}/{n.image}:latest"
    conn = opts.get("connection")
    commands = [
        _snow(["sql", "-f", f"{out}/spcs/setup.sql"], conn),
        _snow(["spcs", "image-registry", "login"], conn),
        ["docker", "build", "--platform", "linux/amd64", "-t", image, out],
        ["docker", "push", image],
        _snow(["sql", "-f", f"{out}/spcs/service.sql"], conn),
    ]
    for cmd in commands:
        status = runner(cmd, {})
        if status != 0:
            raise RuntimeError(f"command failed with exit status {status}: {' '.join(cmd[:3])}")
    return commands


def _doctor(runner: Runner) -> list[str]:
    if not shutil.which("snow"):
        return ["snow (Snowflake CLI) is not on PATH"]
    if runner(["snow", "connection", "test"], {}) != 0:
        return ["snow has no working connection (run snow connection add)"]
    if not shutil.which("docker"):
        return ["docker is not on PATH"]
    return []


register(
    Target(
        id="snowflake_spcs",
        label="Snowflake Snowpark Container Services",
        languages=("python", "r"),
        options=(
            "port",
            "language",
            "service_name",
            "database",
            "schema",
            "compute_pool",
            "instance_family",
            "instances",
            "public",
            "grant_role",
            "private_connectivity",
        ),
        generate=generate,
        private_network_option="private_connectivity",
        apply=_apply,
        doctor=_doctor,
    )
)
