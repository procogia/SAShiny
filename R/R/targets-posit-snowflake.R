# Posit Connect in the Posit Team Native App: target `posit_snowflake` (spec section 6.8.4).
#
# Egress: https://docs.posit.co/partnerships/snowflake/posit-team/networking/egress.html
# Publishing: https://docs.posit.co/partnerships/snowflake/posit-team/connect/publish-outside-snowflake.html
#
# Publishing reuses sas_publish() (spec section 6.7). CRAN: generating writes
# files only; apply = TRUE (never run in checks) publishes with 'rsconnect'.

#' The `snowflake/egress.sql` text (spec section 6.8.4), byte-exact.
#' @noRd
.sashiny_ps_egress <- function(ctx) {
  app <- .sashiny_sf_ident(ctx$options, "application", "POSIT_TEAM")
  schema <- paste0(app, "_APP_DATA.CONFIGURATION")
  integration <- paste0(app, "_CONNECT_EGRESS_EXTERNAL_ACCESS")
  private <- isTRUE(ctx$options$private_connectivity)
  endpoints <- ctx$profile$endpoints
  out <- c(
    sprintf("-- Generated by SAShiny %s (CONTRACT.md 6.8.4). Do not edit by hand.", ctx$version),
    sprintf("-- Lets Posit Connect in the Posit Team Native App %s reach SAS.", app),
    "-- Run as ACCOUNTADMIN or the owner of the integration."
  )
  if (private) {
    out <- c(out, "-- Provision a private endpoint for each host first (SYSTEM$PROVISION_PRIVATELINK_ENDPOINT).")
  }
  out <- c(
    out, "",
    "-- Note the rules in ALLOWED_NETWORK_RULES; SET replaces the list, so keep every rule you need.",
    sprintf("DESCRIBE EXTERNAL ACCESS INTEGRATION %s;", integration),
    ""
  )
  if (private) {
    rules <- stats::setNames(as.list(endpoints), sprintf("%s_SASHINY_SAS_PRIVATE_%d", app, seq_along(endpoints)))
    kind <- "PRIVATE_HOST_PORT"
  } else {
    rules <- stats::setNames(list(endpoints), paste0(app, "_SASHINY_SAS_EGRESS"))
    kind <- "HOST_PORT"
  }
  for (rule in names(rules)) {
    out <- c(
      out,
      sprintf("CREATE OR REPLACE NETWORK RULE %s.%s", schema, rule),
      paste0("  TYPE = ", kind),
      "  MODE = EGRESS",
      sprintf("  VALUE_LIST = (%s);", paste0("'", rules[[rule]], "'", collapse = ", ")),
      ""
    )
  }
  allowed <- c(paste0(schema, ".", app, "_CONNECT_EGRESS_NETWORK_RULE"), paste0(schema, ".", names(rules)))
  out <- c(
    out,
    sprintf("ALTER EXTERNAL ACCESS INTEGRATION %s", integration),
    "  SET ALLOWED_NETWORK_RULES = (",
    paste0(paste0("    ", allowed, collapse = ",\n"), ")"),
    "  ENABLED = TRUE;",
    ""
  )
  paste(out, collapse = "\n")
}

#' The `deploy-posit-snowflake.md` guide text.
#' @noRd
.sashiny_ps_guide <- function(ctx) {
  prof <- ctx$profile
  py <- identical(ctx$language, "python")
  lines <- c(
    "# Deploy to Posit Connect in the Posit Team Native App (Snowflake)",
    "",
    sprintf(
      "Generated by SAShiny %s (CONTRACT.md 6.8.4). Replace every `<...>` placeholder.",
      ctx$version
    ),
    "",
    "Posit manages the runtime: the app is published as ordinary Posit Connect content. To run your own",
    "container in Snowpark Container Services instead, use the `snowflake_spcs` target.",
    "",
    "The app reaches SAS at these host:port pairs; `snowflake/egress.sql` allows them for Connect:",
    "",
    paste("-", prof$endpoints),
    ""
  )
  if (isTRUE(ctx$options$private_connectivity)) {
    lines <- c(
      lines,
      "The SAS profile is reachable only over a private network. `snowflake/egress.sql` creates one",
      "`PRIVATE_HOST_PORT` rule per host; provision a private endpoint for each host first (Business",
      "Critical edition or higher).",
      ""
    )
  }
  if (isTRUE(prof$needs_java)) {
    lines <- c(
      lines,
      "The profile uses IOM, which needs Java 17 in the Connect runtime image. Check this with your Posit",
      "Team administrator.",
      ""
    )
  }
  lines <- c(
    lines,
    "## 1. Allow egress to SAS",
    "",
    "Run `snowflake/egress.sql` in Snowsight, or with `snow sql -f snowflake/egress.sql`.",
    "",
    "## 2. Register the Connect server",
    ""
  )
  if (py) {
    lines <- c(
      lines,
      "Provision a Connect API key, then register the server (rsconnect-python 1.28 or newer):",
      "",
      "```sh",
      "pip install \"rsconnect-python[snowflake]\"",
      "rsconnect add --server \"https://<connect-url>\" --name spcs \\",
      "  --api-key <connect-api-key> --snowflake-connection-name <snowflake-connection>",
      "```",
      ""
    )
  } else {
    lines <- c(
      lines,
      "Provision a Connect API key, then register the server (rsconnect 1.6.1 or newer):",
      "",
      "```r",
      "install.packages(\"rsconnect\")",
      "rsconnect::addServer(\"https://<connect-url>\", name = \"spcs\",",
      "  snowflakeConnectionName = \"<snowflake-connection>\")",
      "rsconnect::connectSPCSUser(server = \"spcs\", apiKey = \"<connect-api-key>\",",
      "  snowflakeConnectionName = \"<snowflake-connection>\")",
      "```",
      ""
    )
  }
  lines <- c(
    lines, "## 3. Publish", "",
    if (length(prof$secrets)) {
      "Set `SASHINY_SAS_USER` and `SASHINY_SAS_PASSWORD` in your session, then publish:"
    } else {
      "Publish:"
    },
    ""
  )
  if (py) {
    lines <- c(
      lines, "```python", "from sashiny.deploy import deploy",
      "deploy(\"<app-dir>\", \"posit_snowflake\", profile=<profile>, license_ack=True, apply=True, server=\"spcs\")",
      "```"
    )
  } else {
    lines <- c(
      lines, "```r",
      "SAShiny::sas_deploy(\"<app-dir>\", \"posit_snowflake\", profile = <profile>, license_ack = TRUE,",
      "  apply = TRUE, server = \"spcs\")",
      "```"
    )
  }
  lines <- c(
    lines, "",
    "Connect stores these environment variables for the content:",
    "",
    sprintf("- %s=%s", names(prof$env), unname(prof$env)),
    if (length(prof$secrets)) sprintf("- %s (secret)", prof$secrets),
    ""
  )
  paste(lines, collapse = "\n")
}

.sashiny_register_target(list(
  id = "posit_snowflake",
  label = "Posit Connect in the Posit Team Native App (Snowflake)",
  languages = c("python", "r"),
  options = c("language", "application", "private_connectivity", "title", "server"),
  private_network_option = "private_connectivity",
  generate = function(ctx) {
    list(
      "snowflake/egress.sql" = .sashiny_ps_egress(ctx),
      "deploy-posit-snowflake.md" = .sashiny_ps_guide(ctx)
    )
  },
  apply = function(ctx, result, runner) {
    if (!identical(ctx$language, "r")) {
      stop("apply for a Python app must run in Python (sashiny.deploy.deploy)", call. = FALSE)
    }
    o <- ctx$options
    server <- o$server
    if (is.null(server) && !(nzchar(Sys.getenv("CONNECT_SERVER")) && nzchar(Sys.getenv("CONNECT_API_KEY")))) {
      stop(
        "apply needs the option server or the environment variables CONNECT_SERVER and CONNECT_API_KEY",
        call. = FALSE
      )
    }
    env <- ctx$profile$env
    # CRAN: the profile's plain variables are set only for the publish call and restored on exit.
    old <- Sys.getenv(names(env), unset = NA)
    do.call(Sys.setenv, as.list(env))
    on.exit(for (n in names(old)) {
      if (is.na(old[[n]])) Sys.unsetenv(n) else do.call(Sys.setenv, as.list(old[n]))
    }, add = TRUE)
    sas_publish(
      file.path(result$out_dir, "bundle"),
      title = o$title, server = server,
      sas_credentials = if (length(ctx$profile$secrets)) "env" else "server",
      license_ack = TRUE, env_vars = names(env)
    )
    list(c("rsconnect::deployApp", file.path(result$out_dir, "bundle")))
  },
  doctor = function(runner) {
    problems <- character(0)
    if (!requireNamespace("rsconnect", quietly = TRUE)) {
      problems <- c(problems, "the 'rsconnect' package is not installed")
    }
    missing <- c("CONNECT_SERVER", "CONNECT_API_KEY")
    missing <- missing[!nzchar(Sys.getenv(missing))]
    if (length(missing)) {
      problems <- c(problems, paste(paste(missing, collapse = " and "), "not set; or pass server"))
    }
    problems
  }
))
