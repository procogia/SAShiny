# Azure Container Apps deployment target (spec section 6.8.1).
#
# CRAN: generating writes files only. The 'az' CLI runs only when the user calls
# sas_deploy(apply = TRUE) or sas_deploy_doctor(); tests use a fake runner.

#' Key Vault secret name for a secret variable (`SASHINY_SAS_USER` -> `sashiny-sas-user`).
#' @noRd
.sashiny_az_secret_name <- function(var) gsub("_", "-", tolower(var), fixed = TRUE)

#' Bicep parameter that holds a secret's Key Vault URI.
#' @noRd
.sashiny_az_secret_param <- function(var) {
  if (endsWith(var, "USER")) "sasUserSecretUri" else "sasPasswordSecretUri"
}

#' Validate the Azure options and return `list(name, replicas, subnet)`.
#' @noRd
.sashiny_az_options <- function(options) {
  name <- options$app_name %||% "sashiny-app"
  if (!is.character(name) || length(name) != 1L || !grepl("^[a-z][a-z0-9-]{1,31}$", name) ||
    endsWith(name, "-")) {
    stop("app_name must be 2-32 lowercase letters, digits or '-', starting with a letter",
      call. = FALSE
    )
  }
  replicas <- options$max_replicas %||% 1L
  if (!is.numeric(replicas) || length(replicas) != 1L || is.na(replicas) ||
    replicas != round(replicas) || replicas < 1 || replicas > 30) {
    stop("max_replicas must be an integer from 1 to 30", call. = FALSE)
  }
  subnet <- options$infrastructure_subnet_id
  if (!is.null(subnet) && (!is.character(subnet) || length(subnet) != 1L ||
    !startsWith(subnet, "/subscriptions/") || grepl("[[:space:]'\"\\\\$`]", subnet))) {
    stop("infrastructure_subnet_id must be a subnet resource id", call. = FALSE)
  }
  list(name = name, replicas = as.integer(replicas), subnet = subnet)
}

#' The `infra/main.bicep` text (spec section 6.8.1), byte-exact.
#' @noRd
.sashiny_az_bicep <- function(ctx) {
  prof <- ctx$profile
  secrets <- prof$secrets
  out <- c(
    sprintf("// Generated by SAShiny %s (CONTRACT.md 6.8.1). Do not edit by hand.", ctx$version),
    "// Azure Container Apps: external ingress with WebSockets (transport auto) and sticky sessions.",
    "// Secrets are Key Vault references; no secret value is stored in this file.",
    "",
    "@description('Container App name.')",
    "param appName string",
    "",
    "@description('Port the app listens on.')",
    "param port int",
    "",
    "@description('Maximum replicas (sticky sessions keep each browser on one replica).')",
    "@minValue(1)",
    "@maxValue(30)",
    "param maxReplicas int",
    "",
    "@description('Existing Azure Container Registry that holds the image.')",
    "param acrName string",
    "",
    "@description('Image tag in the registry.')",
    "param imageTag string = 'latest'",
    ""
  )
  for (var in secrets) {
    out <- c(
      out, sprintf("@description('Key Vault secret URI of %s.')", var),
      paste("param", .sashiny_az_secret_param(var), "string"), ""
    )
  }
  out <- c(
    out,
    "@description('Subnet resource id for VNet integration, or empty for none.')",
    "param infrastructureSubnetId string = ''",
    "",
    "param location string = resourceGroup().location",
    "",
    "resource acr 'Microsoft.ContainerRegistry/registries@2023-07-01' existing = {",
    "  name: acrName",
    "}",
    "",
    "resource identity 'Microsoft.ManagedIdentity/userAssignedIdentities@2023-01-31' = {",
    "  name: '${appName}-id'",
    "  location: location",
    "}",
    "",
    "resource acrPull 'Microsoft.Authorization/roleAssignments@2022-04-01' = {",
    "  name: guid(acr.id, identity.id, 'acrpull')",
    "  scope: acr",
    "  properties: {",
    "    principalId: identity.properties.principalId",
    "    principalType: 'ServicePrincipal'",
    paste0(
      "    roleDefinitionId: subscriptionResourceId('Microsoft.Authorization/roleDefinitions',",
      " '7f951dda-4ed3-4680-a7ca-43fe172d538d')"
    ),
    "  }",
    "}",
    "",
    "resource logs 'Microsoft.OperationalInsights/workspaces@2023-09-01' = {",
    "  name: '${appName}-logs'",
    "  location: location",
    "  properties: {",
    "    sku: {",
    "      name: 'PerGB2018'",
    "    }",
    "    retentionInDays: 30",
    "  }",
    "}",
    "",
    "resource env 'Microsoft.App/managedEnvironments@2025-07-01' = {",
    "  name: '${appName}-env'",
    "  location: location",
    "  properties: {",
    "    appLogsConfiguration: {",
    "      destination: 'log-analytics'",
    "      logAnalyticsConfiguration: {",
    "        customerId: logs.properties.customerId",
    "        sharedKey: logs.listKeys().primarySharedKey",
    "      }",
    "    }",
    "    vnetConfiguration: empty(infrastructureSubnetId) ? null : {",
    "      infrastructureSubnetId: infrastructureSubnetId",
    "    }",
    "  }",
    "}",
    "",
    "resource app 'Microsoft.App/containerApps@2025-07-01' = {",
    "  name: appName",
    "  location: location",
    "  identity: {",
    "    type: 'UserAssigned'",
    "    userAssignedIdentities: {",
    "      '${identity.id}': {}",
    "    }",
    "  }",
    "  dependsOn: [",
    "    acrPull",
    "  ]",
    "  properties: {",
    "    managedEnvironmentId: env.id",
    "    configuration: {",
    "      activeRevisionsMode: 'Single'",
    "      ingress: {",
    "        external: true",
    "        targetPort: port",
    "        transport: 'auto'",
    "        stickySessions: {",
    "          affinity: 'sticky'",
    "        }",
    "      }",
    "      registries: [",
    "        {",
    "          server: acr.properties.loginServer",
    "          identity: identity.id",
    "        }",
    "      ]"
  )
  if (length(secrets)) {
    out <- c(out, "      secrets: [")
    for (var in secrets) {
      out <- c(
        out, "        {",
        sprintf("          name: '%s'", .sashiny_az_secret_name(var)),
        sprintf("          keyVaultUrl: %s", .sashiny_az_secret_param(var)),
        "          identity: identity.id",
        "        }"
      )
    }
    out <- c(out, "      ]")
  }
  out <- c(
    out,
    "    }",
    "    template: {",
    "      containers: [",
    "        {",
    "          name: 'app'",
    "          image: '${acr.properties.loginServer}/${appName}:${imageTag}'",
    "          resources: {",
    "            cpu: json('2.0')",
    "            memory: '4Gi'",
    "          }",
    "          env: ["
  )
  for (name in names(prof$env)) {
    out <- c(
      out, "            {",
      sprintf("              name: '%s'", name),
      sprintf("              value: '%s'", prof$env[[name]]),
      "            }"
    )
  }
  for (var in secrets) {
    out <- c(
      out, "            {",
      sprintf("              name: '%s'", var),
      sprintf("              secretRef: '%s'", .sashiny_az_secret_name(var)),
      "            }"
    )
  }
  out <- c(
    out,
    "          ]",
    "          probes: [",
    "            {",
    "              type: 'Readiness'",
    "              httpGet: {",
    "                path: '/'",
    "                port: port",
    "              }",
    "              periodSeconds: 10",
    "            }",
    "          ]",
    "        }",
    "      ]",
    "      scale: {",
    "        minReplicas: 1",
    "        maxReplicas: maxReplicas",
    "      }",
    "    }",
    "  }",
    "}",
    "",
    "output url string = 'https://${app.properties.configuration.ingress.fqdn}'",
    ""
  )
  paste(out, collapse = "\n")
}

#' The `infra/main.parameters.json` text, formatted like Python's `json.dumps(indent = 2)`.
#' @noRd
.sashiny_az_parameters <- function(name, port, replicas, subnet) {
  params <- c(
    sprintf('    "appName": {\n      "value": "%s"\n    }', name),
    sprintf('    "port": {\n      "value": %d\n    }', as.integer(port)),
    sprintf('    "maxReplicas": {\n      "value": %d\n    }', as.integer(replicas))
  )
  if (!is.null(subnet) && nzchar(subnet)) {
    params <- c(params, sprintf('    "infrastructureSubnetId": {\n      "value": "%s"\n    }', subnet))
  }
  paste0(
    "{\n",
    '  "$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentParameters.json#",\n',
    '  "contentVersion": "1.0.0.0",\n',
    '  "parameters": {\n',
    paste(params, collapse = ",\n"), "\n",
    "  }\n",
    "}\n"
  )
}

#' The `deploy-azure.md` guide text.
#' @noRd
.sashiny_az_guide <- function(ctx, name, subnet) {
  prof <- ctx$profile
  lines <- c(
    "# Deploy to Azure Container Apps",
    "",
    sprintf(
      "Generated by SAShiny %s (CONTRACT.md 6.8.1). Replace every `<...>` placeholder.",
      ctx$version
    ),
    "",
    "The app reaches SAS at these host:port pairs; allow outbound traffic to them:",
    "",
    paste("-", prof$endpoints),
    ""
  )
  if (!is.null(subnet) && nzchar(subnet)) {
    lines <- c(
      lines, sprintf("The environment is integrated with the subnet `%s`,", subnet),
      "which must route to the SAS host.", ""
    )
  }
  if (length(prof$secrets)) {
    lines <- c(
      lines,
      "## 1. Store the SAS credentials in Key Vault",
      "",
      "```sh",
      "az keyvault secret set --vault-name <key-vault> --name sashiny-sas-user --value <sas-user>",
      paste0(
        "az keyvault secret set --vault-name <key-vault> --name sashiny-sas-password ",
        "--value <sas-password>"
      ),
      "```",
      "",
      sprintf("Grant the app's managed identity (`%s-id`, created by the template) the", name),
      paste0(
        "\"Key Vault Secrets User\" role on the vault after the first deployment, then restart",
        " the revision."
      ),
      ""
    )
  }
  secret_args <- if (length(prof$secrets)) {
    paste0(
      " \\\n  sasUserSecretUri=https://<key-vault>.vault.azure.net/secrets/sashiny-sas-user \\\n",
      "  sasPasswordSecretUri=https://<key-vault>.vault.azure.net/secrets/sashiny-sas-password"
    )
  } else {
    ""
  }
  lines <- c(
    lines,
    "## 2. Build the image in your registry",
    "",
    "```sh",
    sprintf("az acr build --registry <acr-name> --image %s:<image-tag> .", name),
    "```",
    "",
    "## 3. Deploy",
    "",
    "```sh",
    "az deployment group create --resource-group <resource-group> \\",
    "  --template-file infra/main.bicep --parameters @infra/main.parameters.json \\",
    paste0("  acrName=<acr-name> imageTag=<image-tag>", secret_args),
    "```",
    "",
    "The deployment output `url` is the app address. Ingress uses WebSockets (transport auto) and",
    "sticky sessions, so each browser stays on one replica.",
    "",
    "## Custom domain (optional)",
    "",
    "Add a CNAME record for your host name pointing to the app's FQDN, and a TXT record",
    "`asuid.<host>` with the environment's custom domain verification id, then run",
    "`az containerapp hostname add` and `az containerapp hostname bind --validation-method CNAME`.",
    ""
  )
  paste(lines, collapse = "\n")
}

.sashiny_register_target(list(
  id = "azure_container_apps",
  label = "Azure Container Apps",
  languages = c("python", "r"),
  options = c("port", "language", "app_name", "max_replicas", "infrastructure_subnet_id"),
  private_network_option = "infrastructure_subnet_id",
  generate = function(ctx) {
    opts <- .sashiny_az_options(ctx$options)
    port <- .sashiny_deploy_port(ctx$options)
    files <- .sashiny_targets[["container"]]$generate(ctx)
    files[["infra/main.bicep"]] <- .sashiny_az_bicep(ctx)
    files[["infra/main.parameters.json"]] <- .sashiny_az_parameters(
      opts$name, port, opts$replicas, opts$subnet
    )
    files[["deploy-azure.md"]] <- .sashiny_az_guide(ctx, opts$name, opts$subnet)
    files
  },
  apply = function(ctx, result, runner) {
    o <- ctx$options
    need <- c("resource_group", "acr_name")
    if (length(ctx$profile$secrets)) need <- c(need, "sas_user_secret_uri", "sas_password_secret_uri")
    missing <- need[vapply(need, function(k) is.null(o[[k]]) || !nzchar(o[[k]]), TRUE)]
    if (length(missing)) {
      stop("apply needs the options ", paste(missing, collapse = ", "), call. = FALSE)
    }
    name <- .sashiny_az_options(o)$name
    tag <- as.character(o$image_tag %||% "latest")
    out <- result$out_dir
    build <- c("az", "acr", "build", "--registry", o$acr_name, "--image", paste0(name, ":", tag), out)
    create <- c(
      "az", "deployment", "group", "create", "--resource-group", o$resource_group,
      "--template-file", paste0(out, "/infra/main.bicep"),
      "--parameters", paste0("@", out, "/infra/main.parameters.json"),
      paste0("acrName=", o$acr_name), paste0("imageTag=", tag)
    )
    if (length(ctx$profile$secrets)) {
      create <- c(
        create, paste0("sasUserSecretUri=", o$sas_user_secret_uri),
        paste0("sasPasswordSecretUri=", o$sas_password_secret_uri)
      )
    }
    commands <- list(build, create)
    for (cmd in commands) {
      status <- runner(cmd, character(0))
      if (!identical(as.integer(status), 0L)) {
        stop(sprintf(
          "command failed with exit status %s: %s", status, paste(cmd[1:4], collapse = " ")
        ), call. = FALSE)
      }
    }
    commands
  },
  doctor = function(runner) {
    if (!nzchar(Sys.which("az"))) {
      return("az (Azure CLI) is not on PATH")
    }
    if (!identical(as.integer(runner(c("az", "account", "show", "--output", "none"), character(0))), 0L)) {
      return("az is not logged in (run az login)")
    }
    character(0)
  }
))
