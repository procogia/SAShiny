# Amazon ECS (Fargate) + ALB deployment target `aws_ecs_express` (spec section 6.8.2).
#
# ECS Express Mode does not expose target-group stickiness or the ALB idle timeout
# (https://docs.aws.amazon.com/AmazonECS/latest/developerguide/express-service-overview.html),
# so the template declares the standard ECS and Elastic Load Balancing resources.
#
# CRAN: generating writes files only. 'docker' and the 'aws' CLI run only when the
# user calls sas_deploy(apply = TRUE) or sas_deploy_doctor(); tests use a fake runner.

#' CloudFormation parameter that holds a secret's Secrets Manager ARN.
#' @noRd
.sashiny_aws_param <- function(var) {
  if (endsWith(var, "USER")) "SasUserSecretArn" else "SasPasswordSecretArn"
}

#' Validate the AWS options and return `list(name, count)`.
#' @noRd
.sashiny_aws_options <- function(options) {
  name <- .sashiny_app_name(options$app_name %||% "sashiny-app")
  count <- options$desired_count %||% 1L
  if (!is.numeric(count) || length(count) != 1L || is.na(count) || count != round(count) ||
    count < 1 || count > 10) {
    .sashiny_abort("deploy", "desired_count must be an integer from 1 to 10")
  }
  public_ip <- if ("public_ip" %in% names(options)) options$public_ip else FALSE
  if (!is.logical(public_ip) || length(public_ip) != 1L || is.na(public_ip)) {
    .sashiny_abort("deploy", "public_ip must be a boolean")
  }
  prefix <- options$role_name_prefix
  boundary <- options$permissions_boundary
  if (!is.null(prefix) && (!is.character(prefix) || length(prefix) != 1L || is.na(prefix) ||
      !grepl("^[A-Za-z0-9_+=,.@-]{1,55}\\z", prefix, perl = TRUE))) {
    .sashiny_abort("deploy", "role_name_prefix must be 1 to 55 IAM role name characters")
  }
  if (!is.null(boundary) && (!is.character(boundary) || length(boundary) != 1L ||
      is.na(boundary) || grepl("'", boundary, fixed = TRUE) ||
      !grepl("^arn:aws(?:-[a-z0-9-]+)?:iam::[0-9]{12}:policy/[!-~]+\\z", boundary, perl = TRUE))) {
    .sashiny_abort("deploy", "permissions_boundary must be an IAM managed policy ARN")
  }
  list(
    name = name, count = as.integer(count), public_ip = public_ip, prefix = prefix,
    boundary = boundary, capability = if (is.null(prefix)) "CAPABILITY_IAM" else "CAPABILITY_NAMED_IAM"
  )
}

#' Optional properties of an ECS IAM role.
#' @noRd
.sashiny_aws_role <- function(options, suffix) {
  c(
    if (!is.null(options$prefix)) sprintf("      RoleName: '%s%s'", options$prefix, suffix),
    if (!is.null(options$boundary)) sprintf("      PermissionsBoundary: '%s'", options$boundary)
  )
}

#' One security-group rule.
#' @noRd
.sashiny_aws_rule <- function(port, source, last = port) {
  c(
    "        - IpProtocol: tcp",
    sprintf("          FromPort: %d", as.integer(port)),
    sprintf("          ToPort: %d", as.integer(last)),
    paste0("          ", source)
  )
}

.sashiny_aws_assume_role <- c(
  "      AssumeRolePolicyDocument:",
  "        Version: '2012-10-17'",
  "        Statement:",
  "          - Effect: Allow",
  "            Principal:",
  "              Service: ecs-tasks.amazonaws.com",
  "            Action: sts:AssumeRole"
)

#' The `infra/template.yaml` text (spec section 6.8.2), byte-exact.
#' @noRd
.sashiny_aws_template <- function(ctx) {
  o <- .sashiny_aws_options(ctx$options)
  name <- o$name
  port <- .sashiny_deploy_port(ctx$options)
  secrets <- ctx$profile$secrets
  ports <- unique(sub("^.*:", "", ctx$profile$endpoints))
  extra <- strsplit(ports[ports != "443"], "-", fixed = TRUE)
  extra <- extra[order(vapply(extra, function(p) as.integer(p[[1L]]), 0L))]
  out <- c(
    sprintf("# Generated by SAShiny %s (CONTRACT.md 6.8.2). Do not edit by hand.", ctx$version),
    "# Standard ECS (Fargate) and ALB resources: ECS Express Mode does not expose target-group",
    "# stickiness or the load balancer idle timeout, which Shiny needs.",
    "# Secrets are Secrets Manager ARNs; no secret value is stored in this file.",
    "AWSTemplateFormatVersion: '2010-09-09'",
    sprintf(
      "Description: SAShiny app %s on Amazon ECS (Fargate) behind an Application Load Balancer.",
      name
    ),
    "",
    "Parameters:",
    "  ImageUri:",
    "    Type: String",
    "    Description: Container image URI in Amazon ECR.",
    "  VpcId:",
    "    Type: AWS::EC2::VPC::Id",
    "    Description: VPC of the subnets.",
    "  PublicSubnetIds:",
    "    Type: List<AWS::EC2::Subnet::Id>",
    paste0(
      "    Description: Subnets of the internet-facing load balancer, in at least two",
      " Availability Zones."
    ),
    if (!o$public_ip) c(
      "  PrivateSubnetIds:",
      "    Type: List<AWS::EC2::Subnet::Id>",
      "    Description: Subnets of the tasks, with outbound access to SAS through a NAT gateway."
    ),
    "  CertificateArn:",
    "    Type: String",
    "    Description: ACM certificate ARN of the HTTPS listener."
  )
  if (length(extra)) {
    out <- c(
      out, "  SasEgressCidr:", "    Type: String", "    Default: 0.0.0.0/0",
      "    Description: CIDR of the SAS hosts, for SAS ports other than 443."
    )
  }
  for (var in secrets) {
    out <- c(
      out, sprintf("  %s:", .sashiny_aws_param(var)), "    Type: String",
      sprintf("    Description: Secrets Manager ARN of %s.", var)
    )
  }
  out <- c(
    out, "",
    "Resources:",
    "  Cluster:",
    "    Type: AWS::ECS::Cluster",
    "    Properties:",
    paste0("      ClusterName: ", name),
    "",
    "  LogGroup:",
    "    Type: AWS::Logs::LogGroup",
    "    Properties:",
    paste0("      LogGroupName: /ecs/", name),
    "      RetentionInDays: 30",
    "",
    "  ExecutionRole:",
    "    Type: AWS::IAM::Role",
    "    Properties:",
    .sashiny_aws_role(o, "execution"),
    .sashiny_aws_assume_role,
    "      ManagedPolicyArns:",
    "        - arn:aws:iam::aws:policy/service-role/AmazonECSTaskExecutionRolePolicy"
  )
  if (length(secrets)) {
    out <- c(
      out,
      "      Policies:",
      "        - PolicyName: read-sas-secrets",
      "          PolicyDocument:",
      "            Version: '2012-10-17'",
      "            Statement:",
      "              - Effect: Allow",
      "                Action: secretsmanager:GetSecretValue",
      "                Resource:",
      paste0("                  - !Ref ", vapply(secrets, .sashiny_aws_param, ""))
    )
  }
  out <- c(
    out, "",
    "  TaskRole:",
    "    Type: AWS::IAM::Role",
    "    Properties:",
    .sashiny_aws_role(o, "task"),
    .sashiny_aws_assume_role,
    "",
    "  LoadBalancerSecurityGroup:",
    "    Type: AWS::EC2::SecurityGroup",
    "    Properties:",
    sprintf("      GroupDescription: %s load balancer", name),
    "      VpcId: !Ref VpcId",
    "      SecurityGroupIngress:",
    .sashiny_aws_rule(443L, "CidrIp: 0.0.0.0/0"),
    "",
    "  ServiceSecurityGroup:",
    "    Type: AWS::EC2::SecurityGroup",
    "    Properties:",
    sprintf("      GroupDescription: %s tasks", name),
    "      VpcId: !Ref VpcId",
    "      SecurityGroupIngress:",
    .sashiny_aws_rule(port, "SourceSecurityGroupId: !Ref LoadBalancerSecurityGroup"),
    "      SecurityGroupEgress:",
    .sashiny_aws_rule(443L, "CidrIp: 0.0.0.0/0")
  )
  for (p in extra) {
    out <- c(out, .sashiny_aws_rule(p[[1L]], "CidrIp: !Ref SasEgressCidr", p[[length(p)]]))
  }
  out <- c(
    out, "",
    "  LoadBalancer:",
    "    Type: AWS::ElasticLoadBalancingV2::LoadBalancer",
    "    Properties:",
    paste0("      Name: ", name),
    "      Type: application",
    "      Scheme: internet-facing",
    "      Subnets: !Ref PublicSubnetIds",
    "      SecurityGroups:",
    "        - !Ref LoadBalancerSecurityGroup",
    "      LoadBalancerAttributes:",
    "        - Key: idle_timeout.timeout_seconds",
    "          Value: '3600'",
    "",
    "  TargetGroup:",
    "    Type: AWS::ElasticLoadBalancingV2::TargetGroup",
    "    Properties:",
    paste0("      Name: ", name),
    "      TargetType: ip",
    "      Protocol: HTTP",
    sprintf("      Port: %d", port),
    "      VpcId: !Ref VpcId",
    "      HealthCheckPath: /",
    "      Matcher:",
    "        HttpCode: '200'",
    "      TargetGroupAttributes:",
    "        - Key: stickiness.enabled",
    "          Value: 'true'",
    "        - Key: stickiness.type",
    "          Value: lb_cookie",
    "        - Key: stickiness.lb_cookie.duration_seconds",
    "          Value: '86400'",
    "",
    "  HttpsListener:",
    "    Type: AWS::ElasticLoadBalancingV2::Listener",
    "    Properties:",
    "      LoadBalancerArn: !Ref LoadBalancer",
    "      Port: 443",
    "      Protocol: HTTPS",
    "      SslPolicy: ELBSecurityPolicy-TLS13-1-2-2021-06",
    "      Certificates:",
    "        - CertificateArn: !Ref CertificateArn",
    "      DefaultActions:",
    "        - Type: forward",
    "          TargetGroupArn: !Ref TargetGroup",
    "",
    "  TaskDefinition:",
    "    Type: AWS::ECS::TaskDefinition",
    "    Properties:",
    paste0("      Family: ", name),
    "      RequiresCompatibilities:",
    "        - FARGATE",
    "      NetworkMode: awsvpc",
    "      Cpu: '2048'",
    "      Memory: '4096'",
    "      RuntimePlatform:",
    "        OperatingSystemFamily: LINUX",
    "        CpuArchitecture: X86_64",
    "      ExecutionRoleArn: !GetAtt ExecutionRole.Arn",
    "      TaskRoleArn: !GetAtt TaskRole.Arn",
    "      ContainerDefinitions:",
    "        - Name: app",
    "          Image: !Ref ImageUri",
    "          User: '10001'",
    "          Essential: true",
    "          HealthCheck:",
    "            Command:",
    "              - CMD-SHELL",
    sprintf("              - 'curl -fsS http://127.0.0.1:%d/ > /dev/null || exit 1'", port),
    "            Interval: 30",
    "            Timeout: 5",
    "            Retries: 3",
    "            StartPeriod: 60",
    "          PortMappings:",
    sprintf("            - ContainerPort: %d", port),
    "              Protocol: tcp",
    "          Environment:"
  )
  env <- ctx$profile$env
  for (key in names(env)) {
    out <- c(out, paste0("            - Name: ", key), sprintf("              Value: '%s'", env[[key]]))
  }
  if (length(secrets)) {
    out <- c(out, "          Secrets:")
    for (var in secrets) {
      out <- c(
        out, paste0("            - Name: ", var),
        paste0("              ValueFrom: !Ref ", .sashiny_aws_param(var))
      )
    }
  }
  out <- c(
    out,
    "          LogConfiguration:",
    "            LogDriver: awslogs",
    "            Options:",
    "              awslogs-group: !Ref LogGroup",
    "              awslogs-region: !Ref AWS::Region",
    "              awslogs-stream-prefix: app",
    "",
    "  Service:",
    "    Type: AWS::ECS::Service",
    "    DependsOn: HttpsListener",
    "    Properties:",
    paste0("      ServiceName: ", name),
    "      Cluster: !Ref Cluster",
    "      LaunchType: FARGATE",
    sprintf("      DesiredCount: %d", o$count),
    "      TaskDefinition: !Ref TaskDefinition",
    "      HealthCheckGracePeriodSeconds: 120",
    "      NetworkConfiguration:",
    "        AwsvpcConfiguration:",
    paste0("          AssignPublicIp: ", if (o$public_ip) "ENABLED" else "DISABLED"),
    paste0("          Subnets: !Ref ", if (o$public_ip) "PublicSubnetIds" else "PrivateSubnetIds"),
    "          SecurityGroups:",
    "            - !Ref ServiceSecurityGroup",
    "      LoadBalancers:",
    "        - ContainerName: app",
    sprintf("          ContainerPort: %d", port),
    "          TargetGroupArn: !Ref TargetGroup",
    "",
    "Outputs:",
    "  Url:",
    "    Description: App address.",
    "    Value: !Sub 'https://${LoadBalancer.DNSName}'",
    "  LoadBalancerDnsName:",
    "    Description: Point your custom domain at this name.",
    "    Value: !GetAtt LoadBalancer.DNSName",
    ""
  )
  paste(out, collapse = "\n")
}

#' The `deploy-aws.md` guide text.
#' @noRd
.sashiny_aws_guide <- function(ctx) {
  o <- .sashiny_aws_options(ctx$options)
  name <- o$name
  prof <- ctx$profile
  registry <- "<account>.dkr.ecr.<region>.amazonaws.com"
  image <- sprintf("%s/%s:<image-tag>", registry, name)
  lines <- c(
    "# Deploy to Amazon ECS (Fargate)",
    "",
    sprintf(
      "Generated by SAShiny %s (CONTRACT.md 6.8.2). Replace every `<...>` placeholder.",
      ctx$version
    ),
    "",
    "The template uses standard ECS and Elastic Load Balancing resources rather than ECS Express Mode,",
    "because Express Mode does not expose target-group stickiness or the load balancer idle timeout,",
    "which Shiny needs.",
    "",
    "The app reaches SAS at these host:port pairs; allow outbound traffic to them:",
    "",
    paste("-", prof$endpoints),
    "",
    if (o$public_ip) c(
      "The tasks use the same public subnets as the load balancer. Supply subnets with a",
      "route to an internet gateway in PublicSubnetIds. Tasks get public IP addresses,",
      "which is less private. The task security group admits only the load balancer.",
      ""
    ) else c(
      "The tasks run in the private subnets, which reach these endpoints through a NAT gateway.",
      ""
    ),
    if (!is.null(o$boundary)) c(
      "Both roles use the configured permissions boundary. Use an existing managed policy",
      "that permits the actions these roles need and satisfies your account guardrails.",
      ""
    ),
    if (!is.null(o$prefix)) c(
      "The role name prefix gives both roles fixed names for account guardrails.",
      "Choose a prefix unique to the stack and acknowledge CAPABILITY_NAMED_IAM.",
      ""
    )
  )
  if (isTRUE(ctx$options$private_network)) {
    lines <- c(
      lines,
      "The SAS profile is reachable only over a private network. Route the task subnets to it through",
      "a Site-to-Site VPN or a Transit Gateway attachment before deploying.",
      ""
    )
  }
  step <- 1L
  if (length(prof$secrets)) {
    lines <- c(
      lines,
      sprintf("## %d. Store the SAS credentials in Secrets Manager", step),
      "",
      "```sh",
      "aws secretsmanager create-secret --name sashiny/sas-user --secret-string <sas-user>",
      "aws secretsmanager create-secret --name sashiny/sas-password --secret-string <sas-password>",
      "```",
      "",
      sprintf("Use the two returned ARNs in step %d.", step + 2L),
      ""
    )
    step <- step + 1L
  }
  lines <- c(
    lines,
    sprintf("## %d. Build and push the image", step),
    "",
    "```sh",
    paste("aws ecr create-repository --repository-name", name),
    paste("aws ecr get-login-password | docker login --username AWS --password-stdin", registry),
    sprintf("docker build --platform linux/amd64 -t %s .", image),
    paste("docker push", image),
    "```",
    "",
    sprintf("## %d. Deploy", step + 1L),
    "",
    "```sh",
    sprintf("aws cloudformation deploy --stack-name %s \\", name),
    sprintf("  --template-file infra/template.yaml --capabilities %s \\", o$capability),
    sprintf("  --parameter-overrides ImageUri=%s \\", image),
    paste0(
      "  VpcId=<vpc-id> PublicSubnetIds=<subnet-a>,<subnet-b>",
      if (!o$public_ip) " PrivateSubnetIds=<subnet-c>,<subnet-d>",
      " \\"
    ),
    if (length(prof$secrets)) {
      c(
        "  CertificateArn=<acm-certificate-arn> \\",
        "  SasUserSecretArn=<sas-user-secret-arn> SasPasswordSecretArn=<sas-password-secret-arn>"
      )
    } else {
      "  CertificateArn=<acm-certificate-arn>"
    },
    "```",
    "",
    "The stack output `Url` is the app address. The load balancer keeps idle WebSockets open for an hour",
    "and uses cookie stickiness, so each browser stays on one task.",
    "",
    "## Custom domain (optional)",
    "",
    "Request or import an ACM certificate for your host name and pass it as `CertificateArn`. Then",
    "create a Route 53 alias record, or a CNAME record at your DNS provider, for the host name that",
    "points to the stack output `LoadBalancerDnsName`.",
    ""
  )
  paste(lines, collapse = "\n")
}

.sashiny_register_target(list(
  id = "aws_ecs_express",
  label = "Amazon ECS (Fargate) with an Application Load Balancer",
  languages = c("python", "r"),
  options = c(
    "port", "language", "app_name", "desired_count", "private_network",
    "permissions_boundary", "role_name_prefix", "public_ip"
  ),
  generate = function(ctx) {
    files <- .sashiny_targets[["container"]]$generate(ctx)
    files[["infra/template.yaml"]] <- .sashiny_aws_template(ctx)
    files[["deploy-aws.md"]] <- .sashiny_aws_guide(ctx)
    files
  },
  apply = function(ctx, result, runner) {
    o <- ctx$options
    config <- .sashiny_aws_options(o)
    need <- c(
      "image_uri", "vpc_id", "public_subnet_ids",
      if (!config$public_ip) "private_subnet_ids", "certificate_arn"
    )
    if (length(ctx$profile$secrets)) need <- c(need, "sas_user_secret_arn", "sas_password_secret_arn")
    missing <- need[vapply(need, function(k) is.null(o[[k]]) || !any(nzchar(o[[k]])), TRUE)]
    if (length(missing)) {
      .sashiny_abort("deploy", "apply needs the options ", paste(missing, collapse = ", "))
    }
    name <- config$name
    out <- result$out_dir
    image <- as.character(o$image_uri)
    deploy <- c(
      "aws", "cloudformation", "deploy",
      "--stack-name", as.character(o$stack_name %||% name),
      "--template-file", paste0(out, "/infra/template.yaml"),
      "--capabilities", config$capability,
      "--parameter-overrides",
      paste0("ImageUri=", image),
      paste0("VpcId=", o$vpc_id),
      paste0("PublicSubnetIds=", paste(o$public_subnet_ids, collapse = ",")),
      if (!config$public_ip) paste0("PrivateSubnetIds=", paste(o$private_subnet_ids, collapse = ",")),
      paste0("CertificateArn=", o$certificate_arn)
    )
    if (length(ctx$profile$secrets)) {
      deploy <- c(
        deploy, paste0("SasUserSecretArn=", o$sas_user_secret_arn),
        paste0("SasPasswordSecretArn=", o$sas_password_secret_arn)
      )
    }
    commands <- list(
      c("docker", "build", "--platform", "linux/amd64", "-t", image, out),
      c("docker", "push", image),
      deploy
    )
    for (cmd in commands) {
      status <- runner(cmd, character(0))
      if (!identical(as.integer(status), 0L)) {
        .sashiny_abort("deploy", sprintf(
          "command failed with exit status %s: %s", status, paste(cmd[1:3], collapse = " ")
        ))
      }
    }
    commands
  },
  doctor = function(runner) {
    if (!nzchar(Sys.which("aws"))) {
      return("aws (AWS CLI) is not on PATH")
    }
    status <- runner(c("aws", "sts", "get-caller-identity", "--output", "text"), character(0))
    if (!identical(as.integer(status), 0L)) {
      return("aws has no valid credentials (run aws configure or aws sso login)")
    }
    if (!nzchar(Sys.which("docker"))) {
      return("docker is not on PATH")
    }
    character(0)
  }
))
