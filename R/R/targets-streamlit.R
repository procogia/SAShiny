# Streamlit in Snowflake target `streamlit_snowflake` (spec section 6.8.5): Python only.
#
# Streamlit is a Python framework, so the R package registers the target only
# to reject it with the spec's error for language r (an R app) and to point
# Python apps to the Python package. R users choose a container-based target.

.sashiny_register_target(list(
  id = "streamlit_snowflake",
  label = "Streamlit in Snowflake (Python only)",
  languages = "python",
  options = c(
    "language", "app_name", "database", "schema", "compute_pool", "warehouse", "title",
    "private_connectivity"
  ),
  private_network_option = "private_connectivity",
  needs_java_runtime = FALSE,
  generate = function(ctx) {
    .sashiny_abort("deploy",
      "target streamlit_snowflake is generated by the Python package ",
      "(sashiny.deploy.deploy); Streamlit has no R front end")
  }
))
