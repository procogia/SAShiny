# Snowpark Container Services deployment target `snowflake_spcs` (spec section 6.8.3).
#
# Specification: https://docs.snowflake.com/en/developer-guide/snowpark-container-services/specification-reference
# Ingress (WebSockets, 90 s idle timeout):
# https://docs.snowflake.com/en/developer-guide/snowpark-container-services/service-network-communications
#
# CRAN: generating writes files only. 'snow' and 'docker' run only when the user
# calls sas_deploy(apply = TRUE) or sas_deploy_doctor(); tests use a fake runner.

#' Validate a Snowflake identifier option.
#' @noRd
.sashiny_sf_ident <- function(options, key, default) {
  value <- options[[key]] %||% default
  if (is.null(value)) {
    return(NULL)
  }
  if (!is.character(value) || length(value) != 1L || is.na(value) ||
    !grepl("^[A-Z][A-Z0-9_]{0,62}$", value)) {
    .sashiny_abort("deploy", key, " must be 1-63 uppercase letters, digits or '_', starting with a letter")
  }
  value
}

#' Validate the Snowflake options and derive the object names.
#' @noRd
.sashiny_sf_names <- function(options) {
  instances <- options$instances %||% 1L
  if (!is.numeric(instances) || length(instances) != 1L || is.na(instances) ||
    instances != round(instances) || instances < 1 || instances > 10) {
    .sashiny_abort("deploy", "instances must be an integer from 1 to 10")
  }
  public <- options$public %||% TRUE
  if (!isTRUE(public) && !isFALSE(public)) {
    .sashiny_abort("deploy", "public must be TRUE or FALSE")
  }
  n <- list(
    service = .sashiny_sf_ident(options, "service_name", "SASHINY_APP"),
    database = .sashiny_sf_ident(options, "database", "SASHINY_DB"),
    schema = .sashiny_sf_ident(options, "schema", "APP"),
    pool = .sashiny_sf_ident(options, "compute_pool", "SASHINY_POOL"),
    family = .sashiny_sf_ident(options, "instance_family", "CPU_X64_S"),
    instances = as.integer(instances),
    public = public,
    grant_role = .sashiny_sf_ident(options, "grant_role", NULL)
  )
  n$image <- gsub("_", "-", tolower(n$service), fixed = TRUE)
  n$fq_schema <- paste0(n$database, ".", n$schema)
  n
}

.sashiny_sf_header <- function(ctx, mark) {
  sprintf("%s Generated by SAShiny %s (CONTRACT.md 6.8.3). Do not edit by hand.", mark, ctx$version)
}

#' The service specification body (without the comment line).
#' @noRd
.sashiny_sf_spec <- function(ctx, n) {
  port <- .sashiny_deploy_port(ctx$options)
  env <- ctx$profile$env
  keys <- c(SASHINY_SAS_USER = "username", SASHINY_SAS_PASSWORD = "password")
  out <- c(
    "spec:",
    "  containers:",
    "    - name: app",
    paste0("      image: ", tolower(sprintf("/%s/%s/sashiny_repo/%s:latest", n$database, n$schema, n$image))),
    "      env:",
    sprintf("        %s: '%s'", names(env), unname(env))
  )
  if (length(ctx$profile$secrets)) {
    out <- c(out, "      secrets:")
    for (var in ctx$profile$secrets) {
      out <- c(
        out,
        "        - snowflakeSecret:",
        sprintf("            objectName: %s_SAS_CREDENTIALS", n$service),
        paste0("          envVarName: ", var),
        paste0("          secretKeyRef: ", keys[[var]])
      )
    }
  }
  out <- c(
    out,
    "      readinessProbe:",
    sprintf("        port: %d", port),
    "        path: /",
    "  endpoints:",
    "    - name: app",
    sprintf("      port: %d", port),
    paste0("      public: ", if (n$public) "true" else "false"),
    ""
  )
  paste(out, collapse = "\n")
}

.sashiny_sf_setup <- function(ctx, n) {
  paste(c(
    .sashiny_sf_header(ctx, "--"),
    "-- Run with a role that can create databases, compute pools and integrations.",
    sprintf("CREATE DATABASE IF NOT EXISTS %s;", n$database),
    sprintf("CREATE SCHEMA IF NOT EXISTS %s;", n$fq_schema),
    sprintf("USE SCHEMA %s;", n$fq_schema),
    "",
    "CREATE IMAGE REPOSITORY IF NOT EXISTS SASHINY_REPO;",
    "",
    sprintf("CREATE COMPUTE POOL IF NOT EXISTS %s", n$pool),
    sprintf("  MIN_NODES = %d", n$instances),
    sprintf("  MAX_NODES = %d", n$instances),
    sprintf("  INSTANCE_FAMILY = %s;", n$family),
    "",
    sprintf("CREATE OR REPLACE NETWORK RULE %s_SAS_EGRESS", n$service),
    "  TYPE = HOST_PORT",
    "  MODE = EGRESS",
    sprintf("  VALUE_LIST = (%s);", paste0("'", ctx$profile$endpoints, "'", collapse = ", ")),
    "",
    sprintf("CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION %s_SAS_ACCESS", n$service),
    sprintf("  ALLOWED_NETWORK_RULES = (%s_SAS_EGRESS)", n$service),
    "  ENABLED = TRUE;",
    "",
    sprintf("SHOW IMAGE REPOSITORIES IN SCHEMA %s;", n$fq_schema),
    ""
  ), collapse = "\n")
}

.sashiny_sf_secret <- function(ctx, n) {
  paste(c(
    .sashiny_sf_header(ctx, "--"),
    "-- Replace the placeholders in a copy, run it once, then delete the copy. Never commit values.",
    sprintf("USE SCHEMA %s;", n$fq_schema),
    sprintf("CREATE OR REPLACE SECRET %s_SAS_CREDENTIALS", n$service),
    "  TYPE = PASSWORD",
    "  USERNAME = '<sas-user>'",
    "  PASSWORD = '<sas-password>';",
    ""
  ), collapse = "\n")
}

.sashiny_sf_service <- function(ctx, n) {
  out <- c(
    .sashiny_sf_header(ctx, "--"),
    sprintf("USE SCHEMA %s;", n$fq_schema),
    sprintf("CREATE SERVICE IF NOT EXISTS %s", n$service),
    sprintf("  IN COMPUTE POOL %s", n$pool),
    sprintf("  MIN_INSTANCES = %d", n$instances),
    sprintf("  MAX_INSTANCES = %d", n$instances),
    sprintf("  EXTERNAL_ACCESS_INTEGRATIONS = (%s_SAS_ACCESS)", n$service),
    "  FROM SPECIFICATION $$",
    paste0(.sashiny_sf_spec(ctx, n), "$$;")
  )
  if (!is.null(n$grant_role)) {
    out <- c(out, sprintf("GRANT SERVICE ROLE %s!ALL_ENDPOINTS_USAGE TO ROLE %s;", n$service, n$grant_role))
  }
  paste(c(out, sprintf("SHOW ENDPOINTS IN SERVICE %s;", n$service), ""), collapse = "\n")
}

.sashiny_sf_guide <- function(ctx, n) {
  prof <- ctx$profile
  lines <- c(
    "# Deploy to Snowflake (Snowpark Container Services)",
    "",
    sprintf(
      "Generated by SAShiny %s (CONTRACT.md 6.8.3). Replace every `<...>` placeholder.",
      ctx$version
    ),
    "",
    "The app reaches SAS at these host:port pairs; `spcs/setup.sql` allows them in a network rule:",
    "",
    paste("-", prof$endpoints),
    ""
  )
  if (isTRUE(ctx$options$private_connectivity)) {
    lines <- c(
      lines,
      "The SAS profile is reachable only over a private network. Configure private connectivity from",
      "Snowflake to it (for example AWS PrivateLink or Azure Private Link) before deploying.",
      ""
    )
  }
  lines <- c(
    lines,
    "The public endpoint is reached through Snowflake sign-in. Ingress supports WebSockets and closes a",
    "connection after 90 seconds without traffic; Shiny's WebSocket heartbeat keeps it open.",
    ""
  )
  if (n$instances > 1L) {
    lines <- c(
      lines,
      sprintf(
        "Warning: the service runs %d instances. Snowflake does not document session affinity between",
        n$instances
      ),
      "instances, so a browser session may move to another instance and lose its state. Use 1 instance",
      "unless you have verified affinity for your account.",
      ""
    )
  }
  step <- 1L
  lines <- c(
    lines,
    sprintf("## %d. Create the objects", step),
    "",
    "```sh",
    "snow sql -f spcs/setup.sql",
    "```",
    "",
    "The last statement shows the image repository; note its `repository_url`.",
    ""
  )
  if (length(prof$secrets)) {
    step <- step + 1L
    lines <- c(
      lines,
      sprintf("## %d. Store the SAS credentials", step),
      "",
      "Copy `spcs/secret.sql`, replace the placeholders in the copy, run it, then delete the copy:",
      "",
      "```sh",
      "snow sql -f <copy-of-secret.sql>",
      "```",
      ""
    )
  }
  lines <- c(
    lines,
    sprintf("## %d. Build and push the image", step + 1L),
    "",
    "```sh",
    "snow spcs image-registry login",
    sprintf("docker build --platform linux/amd64 -t <repository_url>/%s:latest .", n$image),
    sprintf("docker push <repository_url>/%s:latest", n$image),
    "```",
    "",
    sprintf("## %d. Create the service", step + 2L),
    "",
    "```sh",
    "snow sql -f spcs/service.sql",
    "```",
    ""
  )
  if (!is.null(n$grant_role)) {
    lines <- c(
      lines,
      "The last statement shows the endpoint `ingress_url`, the app address. Users need the role",
      sprintf("`%s`, which is granted the endpoint.", n$grant_role),
      ""
    )
  } else {
    lines <- c(lines, "The last statement shows the endpoint `ingress_url`, the app address.", "")
  }
  paste(lines, collapse = "\n")
}

.sashiny_register_target(list(
  id = "snowflake_spcs",
  label = "Snowflake Snowpark Container Services",
  languages = c("python", "r"),
  options = c(
    "port", "language", "service_name", "database", "schema", "compute_pool",
    "instance_family", "instances", "public", "grant_role", "private_connectivity"
  ),
  private_network_option = "private_connectivity",
  generate = function(ctx) {
    n <- .sashiny_sf_names(ctx$options)
    files <- .sashiny_targets[["container"]]$generate(ctx)
    files[["spcs/service-spec.yaml"]] <- paste0(.sashiny_sf_header(ctx, "#"), "\n", .sashiny_sf_spec(ctx, n))
    files[["spcs/setup.sql"]] <- .sashiny_sf_setup(ctx, n)
    if (length(ctx$profile$secrets)) files[["spcs/secret.sql"]] <- .sashiny_sf_secret(ctx, n)
    files[["spcs/service.sql"]] <- .sashiny_sf_service(ctx, n)
    files[["deploy-snowflake-spcs.md"]] <- .sashiny_sf_guide(ctx, n)
    files
  },
  apply = function(ctx, result, runner) {
    o <- ctx$options
    if (is.null(o$repository_url) || !nzchar(o$repository_url)) {
      .sashiny_abort("deploy", "apply needs the options repository_url")
    }
    n <- .sashiny_sf_names(o)
    out <- result$out_dir
    image <- sprintf("%s/%s:latest", sub("/+$", "", o$repository_url), n$image)
    snow <- function(...) {
      cmd <- c("snow", ...)
      if (!is.null(o$connection) && nzchar(o$connection)) cmd <- c(cmd, "--connection", o$connection)
      cmd
    }
    commands <- list(
      snow("sql", "-f", paste0(out, "/spcs/setup.sql")),
      snow("spcs", "image-registry", "login"),
      c("docker", "build", "--platform", "linux/amd64", "-t", image, out),
      c("docker", "push", image),
      snow("sql", "-f", paste0(out, "/spcs/service.sql"))
    )
    for (cmd in commands) {
      status <- runner(cmd, character(0))
      if (!identical(as.integer(status), 0L)) {
        .sashiny_abort("deploy", sprintf(
          "command failed with exit status %s: %s", status, paste(cmd[1:3], collapse = " ")
        ))
      }
    }
    commands
  },
  doctor = function(runner) {
    if (!nzchar(Sys.which("snow"))) {
      return("snow (Snowflake CLI) is not on PATH")
    }
    if (!identical(as.integer(runner(c("snow", "connection", "test"), character(0))), 0L)) {
      return("snow has no working connection (run snow connection add)")
    }
    if (!nzchar(Sys.which("docker"))) {
      return("docker is not on PATH")
    }
    character(0)
  }
))
