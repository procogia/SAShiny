# Databricks Apps target `databricks_apps` (spec section 6.8.6): Python only.
#
# Databricks Apps runs Python (3.11) or Node.js; Shiny for R is not a supported
# framework (https://docs.databricks.com/aws/en/dev-tools/databricks-apps/system-env).
# The R package registers the target only to reject R apps with the spec's
# error and point Python apps to the Python package. R users choose a
# container-based target.

.sashiny_register_target(list(
  id = "databricks_apps",
  label = "Databricks Apps (Python only)",
  languages = "python",
  options = c("language", "app_name", "secret_scope", "private_connectivity"),
  private_network_option = "private_connectivity",
  needs_java_runtime = FALSE,
  generate = function(ctx) {
    .sashiny_abort("deploy",
      "target databricks_apps is generated by the Python package ",
      "(sashiny.deploy.deploy); Databricks Apps does not run R")
  }
))
