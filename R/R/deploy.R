# Deployment targets (spec/CONTRACT.md section 6.8).
#
# `sas_deploy()` turns an app directory into deployment artifacts for one
# hosting platform. `generate` never touches the network or runs a program;
# `apply = TRUE` is a separate step that runs the platform CLI through a
# replaceable command runner; `sas_deploy_doctor()` checks local
# prerequisites. Mirrors `sashiny.deploy`.
#
# CRAN: generating artifacts only writes to the output directory the caller
# names (tests use tempdir()). Nothing here runs during R CMD check except
# with a fake runner.

#' The generated app of a folder without app.R (spec section 6.8).
#' @noRd
.sashiny_generated_app_r <- paste0(
  "# Generated by SAShiny (CONTRACT.md 6.8). Serves every contract in this folder.\n",
  "library(SAShiny)\n",
  "\n",
  "contracts <- sort(list.files(\".\", pattern = \"[.]sashiny[.]yml$\", recursive = TRUE, ",
  "full.names = TRUE))\n",
  "sas_app(contracts, sas_pool(sas_connect_env, max_size = 2L), title = \"SAShiny\")\n"
)

#' The generated app of a folder without app.py (spec section 6.8).
#' @noRd
.sashiny_generated_app_py <- paste0(
  "# Generated by SAShiny (CONTRACT.md 6.8). Serves every contract in this folder.\n",
  "from pathlib import Path\n",
  "\n",
  "import sashiny\n",
  "\n",
  "HERE = Path(__file__).resolve().parent\n",
  "CONTRACTS = sorted(HERE.rglob(\"*.sashiny.yml\"))\n",
  "app = sashiny.app(CONTRACTS, sashiny.Pool(sashiny.connect_from_env, max_size=2), ",
  "title=\"SAShiny\")\n"
)

#' The `.dockerignore` of every container-based target.
#' @noRd
.sashiny_dockerignore <- "*\n!bundle/\n"

#' Validate the `port` option.
#' @noRd
.sashiny_deploy_port <- function(options) {
  port <- options$port %||% 8000L
  if (!is.numeric(port) || length(port) != 1L || is.na(port) || port != round(port) ||
    port < 1 || port > 65535) {
    stop("port must be an integer from 1 to 65535", call. = FALSE)
  }
  as.integer(port)
}

#' The `container` target's Dockerfile (spec section 6.8), byte-exact.
#' @noRd
.sashiny_dockerfile <- function(language, needs_java, port, version) {
  head <- sprintf("# Generated by SAShiny %s (CONTRACT.md 6.8). Do not edit by hand.\n", version)
  tail <- paste0(
    "RUN useradd --create-home --uid 10001 sashiny\n",
    "WORKDIR /app\n",
    "COPY --chown=sashiny:sashiny bundle/ /app/\n",
    "USER sashiny\n",
    sprintf("ENV PORT=%d\n", port),
    sprintf("EXPOSE %d\n", port)
  )
  if (identical(language, "python")) {
    java <- if (needs_java) {
      paste0(
        "RUN apt-get update \\\n",
        " && apt-get install -y --no-install-recommends openjdk-17-jre-headless \\\n",
        " && rm -rf /var/lib/apt/lists/*\n"
      )
    } else {
      ""
    }
    return(paste0(
      head,
      "FROM python:3.12-slim-bookworm\n",
      java,
      sprintf("RUN pip install --no-cache-dir \"sashiny[shiny,saspy,upload,plotnine]==%s\"\n", version),
      tail,
      "HEALTHCHECK --interval=30s --timeout=5s --start-period=30s --retries=3 \\\n",
      "  CMD python -c \"import urllib.request; ",
      sprintf("urllib.request.urlopen('http://127.0.0.1:%d/', timeout=4)\"\n", port),
      "CMD [\"sh\", \"-c\", \"exec shiny run app.py --host 0.0.0.0 --port \\\"$PORT\\\"\"]\n"
    ))
  }
  paste0(
    head,
    "FROM rocker/r-ver:4.5.2\n",
    "RUN apt-get update \\\n",
    " && apt-get install -y --no-install-recommends \\\n",
    if (needs_java) "      openjdk-17-jre-headless \\\n" else "",
    "      python3 python3-venv libpython3-dev curl libcurl4-openssl-dev libssl-dev \\\n",
    " && rm -rf /var/lib/apt/lists/*\n",
    "RUN python3 -m venv /opt/saspy \\\n",
    " && /opt/saspy/bin/pip install --no-cache-dir \"saspy>=5.100\" \"pandas>=2.0\"\n",
    "ENV RETICULATE_PYTHON=/opt/saspy/bin/python\n",
    "RUN Rscript -e 'pkgs <- c(\"remotes\", \"shiny\", \"bslib\", \"callr\", \"later\", ",
    "\"promises\", \"reticulate\", \"ggplot2\"); install.packages(pkgs); ",
    "stopifnot(all(vapply(pkgs, requireNamespace, TRUE, quietly = TRUE)), ",
    "packageVersion(\"reticulate\") >= \"1.45.0\")' \\\n",
    sprintf(
      paste0(
        " && Rscript -e 'remotes::install_github(\"procogia/SAShiny/R@r-v%s\", ",
        "upgrade = \"never\"); ",
        "stopifnot(requireNamespace(\"SAShiny\", quietly = TRUE))'\n"
      ),
      version
    ),
    tail,
    "HEALTHCHECK --interval=30s --timeout=5s --start-period=60s --retries=3 \\\n",
    sprintf("  CMD curl -fsS \"http://127.0.0.1:%d/\" > /dev/null || exit 1\n", port),
    "CMD [\"sh\", \"-c\", \"exec Rscript -e \\\"shiny::runApp('/app', host = '0.0.0.0', ",
    "port = as.integer(Sys.getenv('PORT')))\\\"\"]\n"
  )
}

#' The deployment target registry.
#' @noRd
.sashiny_targets <- new.env(parent = emptyenv())

#' Add a target to the registry.
#'
#' A target is a list with `id`, `label`, `languages`, `options`, `generate`
#' (a function of the deploy context returning a named list of file texts),
#' and optionally `private_network_option` (default `"private_network"`),
#' `needs_java_runtime` (default `TRUE`), `apply` and `doctor`.
#' @noRd
.sashiny_register_target <- function(target) {
  # Runs while the package loads, before utils.R (and its `%||%`) is collated.
  if (is.null(target$private_network_option)) target$private_network_option <- "private_network"
  if (is.null(target$needs_java_runtime)) target$needs_java_runtime <- TRUE
  assign(target$id, target, envir = .sashiny_targets)
  invisible(target)
}

.sashiny_register_target(list(
  id = "container",
  label = "Container image (Dockerfile)",
  languages = c("python", "r"),
  options = c("port", "language", "private_network"),
  generate = function(ctx) {
    port <- .sashiny_deploy_port(ctx$options)
    list(
      "Dockerfile" = .sashiny_dockerfile(ctx$language, ctx$profile$needs_java, port, ctx$version),
      ".dockerignore" = .sashiny_dockerignore
    )
  },
  doctor = function(runner) {
    if (nzchar(Sys.which("docker"))) character(0) else "docker is not on PATH (needed only to build)"
  }
))

#' List the deployment targets
#'
#' @return A data frame with one row per target: `id`, `label` and
#'   `languages` (comma-separated), in id order.
#' @examples
#' sas_deploy_targets()
#' @export
sas_deploy_targets <- function() {
  ids <- sort(ls(.sashiny_targets))
  data.frame(
    id = ids,
    label = vapply(ids, function(i) .sashiny_targets[[i]]$label, ""),
    languages = vapply(ids, function(i) paste(.sashiny_targets[[i]]$languages, collapse = ", "), ""),
    row.names = NULL,
    stringsAsFactors = FALSE
  )
}

#' Look up a registered target.
#' @noRd
.sashiny_lookup_target <- function(target) {
  if (!is.character(target) || length(target) != 1L || !exists(target, envir = .sashiny_targets)) {
    stop(sprintf(
      "unknown deployment target '%s'; expected one of %s",
      paste(target, collapse = ","), paste(sort(ls(.sashiny_targets)), collapse = ", ")
    ), call. = FALSE)
  }
  get(target, envir = .sashiny_targets)
}

#' Detect the app language (spec section 6.8).
#' @return `list(language, generated)`.
#' @noRd
.sashiny_deploy_language <- function(app_dir, requested) {
  has_py <- file.exists(file.path(app_dir, "app.py"))
  has_r <- file.exists(file.path(app_dir, "app.R"))
  if (!is.null(requested)) {
    if (!requested %in% c("python", "r")) {
      stop("language must be 'python' or 'r'", call. = FALSE)
    }
    return(list(language = requested, generated = !(if (requested == "python") has_py else has_r)))
  }
  if (has_py != has_r) {
    return(list(language = if (has_py) "python" else "r", generated = FALSE))
  }
  stop(
    "cannot detect the app language: the folder has ",
    if (has_py) "both app.py and app.R" else "neither app.py nor app.R",
    "; pass language = \"python\" or language = \"r\"",
    call. = FALSE
  )
}

#' The default command runner: runs a command and returns its exit status.
#'
#' CRAN: runs only from `apply = TRUE` or `sas_deploy_doctor()`, never during
#' checks (tests pass a fake runner).
#' @noRd
.sashiny_system_runner <- function(args, env = character(0)) {
  status <- system2(args[[1]], args[-1], env = if (length(env)) paste0(names(env), "=", env) else character(0))
  as.integer(status %||% 0L)
}

#' Generate (and optionally apply) deployment artifacts
#'
#' Turns an app directory into deployment artifacts for one hosting platform
#' (spec section 6.8). Generating never touches the network: it writes the
#' bundle (the app's files, without credential files) and the target's
#' artifacts to `out_dir`. With `apply = TRUE` the target's platform CLI is run
#' afterwards.
#'
#' @section Licence:
#' Deploying requires `license_ack = TRUE`: you confirm that the deployed app
#' runs programs only on a 'SAS' system you are licensed to use. The deployed
#' app gets `SASHINY_LICENSE_ACK=true` (spec section 6.6).
#'
#' @section Secrets:
#' Credential files are never bundled, and generated files contain only the
#' names of secret variables (`SASHINY_SAS_USER`, `SASHINY_SAS_PASSWORD`).
#' Their values come from the platform's secret store.
#'
#' @param app_dir The app directory: `app.R` or `app.py` with its contracts and
#'   programs, or only contracts (an app that serves all of them is generated).
#' @param target A target id from [sas_deploy_targets()].
#' @param out_dir Output directory; created, and must be empty or absent.
#'   Defaults to `<app_dir>-deploy-<target>` next to the app directory.
#' @param profile The 'SAS' connection profile: a list accepted by
#'   [sas_profile()], or a `sashiny_profile`.
#' @param ... Target options, for example `port`, `language` or
#'   `private_network`.
#' @param license_ack Must be `TRUE`; see the "Licence" section.
#' @param apply Also run the platform CLI.
#' @param runner Command runner for `apply`: a function `function(args, env)`
#'   returning an exit status. Defaults to [system2()].
#' @param version 'SAShiny' version written into artifacts (defaults to the
#'   installed version; the spec fixtures use `"0.0.0"`).
#' @return Invisibly, a `sashiny_deployment` list with `target`, `language`,
#'   `out_dir`, `files`, `excluded`, `env`, `secrets`, `endpoints` and
#'   `commands`.
#' @examples
#' app <- file.path(tempdir(), "sashiny-deploy-example")
#' dir.create(app, showWarnings = FALSE)
#' file.copy(system.file("examples", "minimal", c("minimal.sas", "minimal.sashiny.yml"),
#'   package = "SAShiny"
#' ), app, overwrite = TRUE)
#' out <- tempfile("sashiny-container-")
#' res <- sas_deploy(app, "container", out,
#'   profile = list(name = "oda", method = "iom", oda_region = "us1"),
#'   language = "r", license_ack = TRUE
#' )
#' res$files
#' cat(readLines(file.path(out, "Dockerfile"), n = 3), sep = "\n")
#' @export
sas_deploy <- function(app_dir, target, out_dir = NULL, profile = NULL, ...,
                       license_ack = FALSE, apply = FALSE, runner = NULL, version = NULL) {
  spec <- .sashiny_lookup_target(target)
  options <- list(...)
  ctx <- .sashiny_deploy_validate(spec, app_dir, profile, license_ack, version, options)
  artifacts <- spec$generate(ctx)
  if (ctx$generated) {
    name <- if (identical(ctx$language, "python")) "bundle/app.py" else "bundle/app.R"
    artifacts[[name]] <- if (identical(ctx$language, "python")) {
      .sashiny_generated_app_py
    } else {
      .sashiny_generated_app_r
    }
  }
  out <- out_dir %||% file.path(dirname(ctx$app_dir), paste0(basename(ctx$app_dir), "-deploy-", target))
  written <- .sashiny_deploy_write(ctx$app_dir, out, artifacts)
  prof <- ctx$profile
  result <- structure(list(
    target = target,
    language = ctx$language,
    out_dir = out,
    files = written$files,
    excluded = written$excluded,
    env = prof$env,
    secrets = prof$secrets,
    endpoints = prof$endpoints,
    commands = list()
  ), class = "sashiny_deployment")
  if (isTRUE(apply)) {
    if (is.null(spec$apply)) {
      stop(sprintf("target %s has no apply step; follow its generated docs", target), call. = FALSE)
    }
    result$commands <- spec$apply(ctx, result, runner %||% .sashiny_system_runner)
  }
  invisible(result)
}

#' Run the section 6.8 checks in order and build the deploy context.
#' @noRd
.sashiny_deploy_validate <- function(spec, app_dir, profile, license_ack, version, options) {
  if (!isTRUE(license_ack)) {
    stop(
      "deploying requires license_ack = TRUE: confirm the deployed app runs programs only on a ",
      "'SAS' system you are licensed to use",
      call. = FALSE
    )
  }
  if (is.null(profile)) {
    stop("a SAS connection profile is required", call. = FALSE)
  }
  prof <- if (inherits(profile, "sashiny_profile")) profile else sas_profile(profile)
  private <- options[[spec$private_network_option]]
  has_private <- !is.null(private) && !isFALSE(private) && !identical(private, "") && !anyNA(private)
  if (isTRUE(prof$requires_vpn) && !has_private) {
    stop(sprintf(
      "profile %s requires a private network; pass %s for target %s",
      prof$name, spec$private_network_option, spec$id
    ), call. = FALSE)
  }
  if (isTRUE(prof$needs_java) && !isTRUE(spec$needs_java_runtime)) {
    stop(sprintf(
      "target %s cannot provide Java 17, which profile %s (iom) needs; use an http (Viya) profile",
      spec$id, prof$name
    ), call. = FALSE)
  }
  if (!is.null(options$port)) .sashiny_deploy_port(options)
  root <- normalizePath(app_dir, winslash = "/", mustWork = TRUE)
  lang <- .sashiny_deploy_language(root, options$language)
  if (!lang$language %in% spec$languages) {
    stop(sprintf("target %s does not support language %s", spec$id, lang$language), call. = FALSE)
  }
  list(
    app_dir = root, profile = prof, language = lang$language, generated = lang$generated,
    options = options, version = version %||% as.character(utils::packageVersion("SAShiny"))
  )
}

#' Copy the bundle and write the artifacts (LF line endings, UTF-8).
#' @noRd
.sashiny_deploy_write <- function(root, out, artifacts) {
  if (dir.exists(out) && length(list.files(out, all.files = TRUE, no.. = TRUE)) > 0L) {
    stop("out_dir must be empty or absent: ", out, call. = FALSE)
  }
  bundle <- .sashiny_bundle_files(root)
  written <- character(0)
  for (rel in bundle$files) {
    dest <- file.path(out, "bundle", rel)
    dir.create(dirname(dest), recursive = TRUE, showWarnings = FALSE)
    file.copy(file.path(root, rel), dest, overwrite = TRUE)
    written <- c(written, paste0("bundle/", rel))
  }
  for (rel in names(artifacts)) {
    dest <- file.path(out, rel)
    dir.create(dirname(dest), recursive = TRUE, showWarnings = FALSE)
    writeBin(charToRaw(enc2utf8(artifacts[[rel]])), dest)
    written <- c(written, rel)
  }
  list(files = .sashiny_sort_bytes(unique(written)), excluded = bundle$excluded)
}

#' @export
print.sashiny_deployment <- function(x, ...) {
  cat("<sashiny deployment: ", x$target, " (", x$language, ")>\n", sep = "")
  cat("  out_dir:", x$out_dir, "\n")
  cat("  files:", length(x$files), "| excluded:", length(x$excluded), "\n")
  cat("  egress:", paste(x$endpoints, collapse = ", "), "\n")
  cat("  secrets (names only):", if (length(x$secrets)) paste(x$secrets, collapse = ", ") else "none", "\n")
  invisible(x)
}

#' Check local prerequisites for a deployment target
#'
#' Reports missing tools or environment variables by name only, never values.
#'
#' @param target A target id from [sas_deploy_targets()].
#' @param runner Command runner (see [sas_deploy()]).
#' @return A character vector of problems; empty when ready.
#' @examples
#' sas_deploy_doctor("container")
#' @export
sas_deploy_doctor <- function(target, runner = NULL) {
  spec <- .sashiny_lookup_target(target)
  if (is.null(spec$doctor)) character(0) else spec$doctor(runner %||% .sashiny_system_runner)
}
